/**
 * Presentación de marcadores (D01-D15, F09, J10).
 *
 * Todo lo que decide cómo se ve un marcador —su tamaño, su texto, si se muestra
 * en este dispositivo, cómo se deforma una imagen proyectada sobre la
 * panorámica— está aquí y no en el componente. El motivo es el de siempre en
 * este proyecto: es aritmética que se puede equivocar de forma plausible. Una
 * imagen proyectada con la matriz mal calculada no se ve rota, se ve
 * *ligeramente* mal, y nadie lo detecta mirando una captura.
 */
import type {
  DeviceKind,
  Hotspot,
  HotspotGeometry,
  ProjectionMode,
  Transform3d,
  Uv,
} from '@it360/domain';

/* ------------------------------------------------------------------ *
 * Texto con variables (D02, F09, J10)
 * ------------------------------------------------------------------ */

/**
 * Contexto de sustitución de variables.
 *
 * Es deliberadamente plano y pequeño. Un contexto que expusiera el proyecto
 * entero convertiría una plantilla de texto en una vía para leer cualquier
 * dato del recorrido, incluido el que no se publica.
 */
export interface TemplateContext {
  readonly scene?: { readonly title?: string; readonly index?: number; readonly total?: number };
  readonly asset?: {
    readonly tag?: string;
    readonly name?: string;
    readonly manufacturer?: string;
    readonly model?: string;
  };
  /** Puntuaciones de la sesión (J10). */
  readonly score?: Readonly<Record<string, number>>;
  /** Última lectura de la variable asociada, ya formateada. */
  readonly telemetry?: Readonly<Record<string, string>>;
  /** Tiempo transcurrido de la sesión, ya formateado. */
  readonly time?: { readonly elapsed?: string; readonly remaining?: string };
}

const PLACEHOLDER = /\{\{\s*([a-zA-Z][a-zA-Z0-9_.]*)\s*\}\}/g;

/**
 * Sustituye `{{ruta.de.la.variable}}` por su valor.
 *
 * Una variable que no existe se deja **visible** como `{{nombre}}` en lugar de
 * sustituirse por una cadena vacía. Borrarla silenciosamente produce etiquetas
 * a medias —«Presión: bar»— que el autor no sabe por qué salen así; dejarla a
 * la vista señala exactamente qué escribió mal.
 *
 * El recorrido es de sólo lectura: no se evalúa nada, sólo se busca la ruta en
 * el contexto. No hay forma de que una plantilla ejecute código.
 */
export function resolveTemplate(template: string, context: TemplateContext): string {
  return template.replace(PLACEHOLDER, (match, path: string) => {
    const value = lookup(context, path.split('.'));
    if (value === undefined || value === null) return match;
    return String(value);
  });
}

function lookup(source: unknown, path: readonly string[]): unknown {
  let current: unknown = source;
  for (const key of path) {
    if (current === null || typeof current !== 'object') return undefined;
    current = (current as Record<string, unknown>)[key];
  }
  return current;
}

/** `true` si la plantilla deja alguna variable sin resolver. */
export function hasUnresolvedVariables(resolved: string): boolean {
  return PLACEHOLDER.test(resolved);
}

/* ------------------------------------------------------------------ *
 * Visibilidad por dispositivo (D14)
 * ------------------------------------------------------------------ */

export function isVisibleOnDevice(hotspot: Hotspot, device: DeviceKind): boolean {
  return hotspot.visibility[device];
}

/**
 * Marcadores que se muestran en un dispositivo, en orden de dibujo.
 *
 * El orden importa: dos marcadores que se solapan se pulsan por el que queda
 * encima, y con un orden inestable el visitante pulsa uno distinto cada vez
 * que entra en la escena. Se ordena por el campo `order` del autor y, a
 * igualdad, por identificador, que es estable.
 */
export function visibleHotspots(
  hotspots: readonly Hotspot[],
  device: DeviceKind,
  options: { readonly includeUnreviewed?: boolean; readonly inEditor?: boolean } = {},
): readonly Hotspot[] {
  return hotspots
    .filter((hotspot) => {
      if (!isVisibleOnDevice(hotspot, device)) return false;
      if (hotspot.hiddenInEditor && options.inEditor === true) return false;
      if (hotspot.autoGenerated && !hotspot.reviewed && options.includeUnreviewed !== true) {
        return false;
      }
      return true;
    })
    .slice()
    .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
}

/* ------------------------------------------------------------------ *
 * Precarga (D14)
 * ------------------------------------------------------------------ */

export type PreloadTrigger = 'sceneEnter' | 'hover' | 'activate';

/**
 * Decide si hay que cargar ya el contenido de un marcador.
 *
 * Precargar todo satura la red y retrasa la primera imagen, que es lo único
 * que el visitante está esperando. Precargar nada hace que cada clic espere.
 * El autor elige por marcador y esta función aplica su elección.
 */
export function shouldPreload(hotspot: Hotspot, trigger: PreloadTrigger): boolean {
  switch (hotspot.preload) {
    case 'eager':
      return true;
    case 'onHover':
      return trigger === 'hover' || trigger === 'activate';
    case 'lazy':
      return trigger === 'activate';
    default:
      return false;
  }
}

/* ------------------------------------------------------------------ *
 * Escala y proyección (D07)
 * ------------------------------------------------------------------ */

export interface ScaleInput {
  readonly hotspot: Hotspot;
  /** Escala que impone la perspectiva en este punto de la pantalla. */
  readonly projectionScale: number;
  readonly hovered: boolean;
}

/**
 * Escala final de un marcador.
 *
 * Los tres modos de proyección responden a necesidades distintas:
 *
 * - `sticker`: adherido a la escena. Escala con la perspectiva, así que un
 *   marcador sobre una tubería lejana se ve pequeño. Es lo que da sensación de
 *   pertenecer al espacio.
 * - `billboard`: de frente al observador, con tamaño constante. Siempre
 *   legible, no se integra.
 * - `floating`: fijo en pantalla. Ni escala ni se mueve con la cámara; es para
 *   controles, no para señalar cosas.
 *
 * El factor de la perspectiva se acota: sin límite inferior, un marcador en el
 * borde de una panorámica de 100° de campo se reduce a dos píxeles y el
 * visitante no puede pulsarlo aunque esté visible.
 */
export function effectiveScale({ hotspot, projectionScale, hovered }: ScaleInput): number {
  const base = hotspot.style.transform.scale;
  const hover = hovered ? hotspot.style.hoverScale : 1;

  const perspective =
    hotspot.style.projection === 'sticker'
      ? Math.min(Math.max(projectionScale, 0.35), 3)
      : 1;

  return base * hover * perspective;
}

/** Tamaño en píxeles del marcador antes de escalar. */
export function baseSizePx(geometry: HotspotGeometry): number {
  switch (geometry.shape) {
    case 'icon':
      return geometry.sizePx;
    case 'text':
      // El alto lo decide el texto; el ancho se limita para que una etiqueta
      // larga no cruce la pantalla entera.
      return Math.min(geometry.maxWidthPx, 1200);
    case 'webframe':
      return geometry.widthPx;
    case 'model':
      return Math.round(64 * geometry.sizeScale);
    default:
      return 40;
  }
}


/* ------------------------------------------------------------------ *
 * Transformación del marcador (D07, D08, D09)
 * ------------------------------------------------------------------ */

export interface MarkerTransformInput {
  readonly transform: Transform3d;
  readonly projection: ProjectionMode;
  /** Escala ya resuelta por `effectiveScale`. */
  readonly appliedScale: number;
}

/**
 * Transformación CSS de un marcador puntual.
 *
 * Los tres ejes sólo se aplican donde se notan, y es la misma regla que la
 * interfaz de autoría le enseña al autor (`axisAffectsRender` en el dominio):
 * un marcador «de frente» mira siempre al observador, así que inclinarlo o
 * girarlo sobre su eje vertical no puede cambiar lo que se ve. Aplicar esas
 * rotaciones ahí produciría un marcador deformado que contradice lo que la
 * pantalla de edición promete.
 *
 * La `perspective` sólo se añade cuando hay rotación fuera del plano: una
 * declaración de perspectiva en todos los marcadores fuerza una capa de
 * composición por marcador, y en una escena con cincuenta se nota.
 *
 * **Límite declarado:** `depth` se aplica como escala, no como paralaje. Este
 * dibujo es en espacio de pantalla sobre una panorámica y no hay geometría
 * donde desplazar el marcador en profundidad de verdad; acercarlo o alejarlo
 * se traduce en que se vea mayor o menor, que es la parte observable del
 * efecto. Lo que no hace es moverse respecto al fondo al girar la cámara.
 */
export function markerTransform({
  transform,
  projection,
  appliedScale,
}: MarkerTransformInput): string {
  const scale = appliedScale * depthScale(transform.depth);
  const parts = [`translate(-50%, -50%)`];

  const spatial = projection !== 'billboard';
  const tilt = spatial ? transform.tilt : 0;
  const spin = spatial ? transform.spin : 0;
  const needsPerspective = Math.abs(tilt) > 1e-6 || Math.abs(spin) > 1e-6;

  if (needsPerspective) parts.push('perspective(600px)');

  parts.push(`scale(${scale.toFixed(3)})`);

  if (Math.abs(tilt) > 1e-6) parts.push(`rotateX(${tilt.toFixed(4)}rad)`);
  if (Math.abs(spin) > 1e-6) parts.push(`rotateY(${spin.toFixed(4)}rad)`);
  if (Math.abs(transform.roll) > 1e-6) parts.push(`rotateZ(${transform.roll.toFixed(4)}rad)`);

  return parts.join(' ');
}

/**
 * Escala equivalente a la profundidad.
 *
 * `depth` va de 0,1 a 10 siendo 1 el tamaño nominal. Se usa la raíz para que
 * el extremo del rango no multiplique el marcador por diez: a 10 ocuparía más
 * que la pantalla y taparía la escena que señala.
 */
export const depthScale = (depth: number): number => Math.sqrt(Math.min(Math.max(depth, 0.1), 10));

/* ------------------------------------------------------------------ *
 * Polígonos (D03, D11)
 * ------------------------------------------------------------------ */

/** Proyección de un punto UV de la panorámica a píxeles de pantalla. */
export type UvProjector = (uv: Uv) => { readonly x: number; readonly y: number } | null;

/**
 * Contorno de un polígono en coordenadas de pantalla.
 *
 * Devuelve `null` cuando alguno de los vértices queda detrás de la cámara: un
 * polígono con un vértice sin proyección válida se dibujaría con ese vértice en
 * un punto arbitrario, produciendo una forma que no corresponde a nada y que
 * además capturaría clics donde no debe.
 */
export function polygonScreenPoints(
  points: readonly Uv[],
  project: UvProjector,
): readonly { readonly x: number; readonly y: number }[] | null {
  const projected: { x: number; y: number }[] = [];
  for (const uv of points) {
    const screen = project(uv);
    if (screen === null) return null;
    projected.push({ x: screen.x, y: screen.y });
  }
  return projected;
}

/**
 * Atributo `clip-path` de un polígono, en píxeles.
 *
 * Un polígono invertido (D11) activa todo lo que queda **fuera** del contorno.
 * Se consigue con la regla de relleno alterno: un rectángulo que cubre la
 * pantalla más el contorno interior, de modo que el interior queda excluido.
 */
export function polygonClipPath(
  screenPoints: readonly { readonly x: number; readonly y: number }[],
  options: { readonly inverted?: boolean; readonly width?: number; readonly height?: number } = {},
): string {
  const inner = screenPoints.map((p) => `${p.x.toFixed(1)}px ${p.y.toFixed(1)}px`).join(', ');

  if (options.inverted !== true) return `polygon(${inner})`;

  const width = options.width ?? 10_000;
  const height = options.height ?? 10_000;
  const outer = `0px 0px, ${width}px 0px, ${width}px ${height}px, 0px ${height}px`;
  return `polygon(evenodd, ${outer}, ${inner})`;
}

/**
 * `true` si el punto está dentro del polígono.
 *
 * Algoritmo del número de cruces. Se usa para decidir si un clic cae dentro,
 * en lugar de confiar en el `clip-path` del navegador: con `clip-path`, el
 * área de pulsación de un polígono invertido incluye todo el rectángulo, y el
 * visitante activaría el marcador pulsando cualquier parte de la pantalla.
 */
export function pointInPolygon(
  point: { readonly x: number; readonly y: number },
  polygon: readonly { readonly x: number; readonly y: number }[],
): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i, i += 1) {
    const a = polygon[i];
    const b = polygon[j];
    if (a === undefined || b === undefined) continue;

    const crosses = a.y > point.y !== b.y > point.y;
    if (!crosses) continue;

    const at = a.x + ((point.y - a.y) / (b.y - a.y)) * (b.x - a.x);
    if (point.x < at) inside = !inside;
  }
  return inside;
}

/* ------------------------------------------------------------------ *
 * Imagen proyectada (D05)
 * ------------------------------------------------------------------ */

export interface Quad {
  readonly topLeft: { readonly x: number; readonly y: number };
  readonly topRight: { readonly x: number; readonly y: number };
  readonly bottomRight: { readonly x: number; readonly y: number };
  readonly bottomLeft: { readonly x: number; readonly y: number };
}

/**
 * Transformación CSS que lleva una imagen rectangular a un cuadrilátero.
 *
 * Es el requisito D05: una imagen «ajustada al panorama», por ejemplo un plano
 * pegado sobre una pared o una etiqueta sobre un equipo. La imagen es
 * rectangular y la superficie de destino, vista en perspectiva, es un
 * cuadrilátero cualquiera.
 *
 * Una transformación afín —escalar, rotar, inclinar— no puede hacer esto: no
 * puede convertir un rectángulo en un trapecio. Hace falta una homografía, que
 * en CSS se expresa con `matrix3d`. La matriz se calcula resolviendo el sistema
 * de ocho ecuaciones que lleva las cuatro esquinas del cuadrado unidad a las
 * cuatro del destino.
 *
 * Devuelve `null` cuando el sistema es degenerado —tres esquinas alineadas, o
 * el cuadrilátero colapsado—, en lugar de una matriz con infinitos que el
 * navegador interpretaría como «no dibujar nada» sin explicación.
 */
export function quadTransform(
  width: number,
  height: number,
  quad: Quad,
): string | null {
  if (width <= 0 || height <= 0) return null;

  const source: readonly [number, number][] = [
    [0, 0],
    [width, 0],
    [width, height],
    [0, height],
  ];
  const target: readonly [number, number][] = [
    [quad.topLeft.x, quad.topLeft.y],
    [quad.topRight.x, quad.topRight.y],
    [quad.bottomRight.x, quad.bottomRight.y],
    [quad.bottomLeft.x, quad.bottomLeft.y],
  ];

  const matrix = solveHomography(source, target);
  if (matrix === null) return null;

  const [a, b, c, d, e, f, g, h] = matrix;

  // CSS `matrix3d` es columna-mayor y 4×4. La homografía 2D se coloca en las
  // filas y columnas que corresponden a x, y y w; la tercera dimensión queda
  // como identidad porque la imagen es plana.
  const values: readonly number[] = [
    a ?? 0, d ?? 0, 0, g ?? 0,
    b ?? 0, e ?? 0, 0, h ?? 0,
    0, 0, 1, 0,
    c ?? 0, f ?? 0, 0, 1,
  ];
  /**
   * Se emite con toda la precisión del número, no redondeado.
   *
   * Los coeficientes de perspectiva son del orden de 1e-4, y redondearlos a
   * seis decimales desplaza las esquinas de una imagen de 2000 px varios
   * píxeles: justo el error que no se ve en una captura y sí se nota al girar
   * la vista, porque la imagen «resbala» sobre la superficie.
   */
  return `matrix3d(${values
    .map((v) => (Number.isFinite(v) ? String(Number(v.toPrecision(15))) : '0'))
    .join(', ')})`;
}

/**
 * Resuelve la homografía que lleva cuatro puntos a otros cuatro.
 *
 * Sistema de 8×8 por eliminación de Gauss con pivoteo parcial. El pivoteo no
 * es un lujo: sin él, un cuadrilátero con una esquina en el origen produce un
 * pivote nulo y la solución sale con infinitos.
 */
function solveHomography(
  source: readonly (readonly [number, number])[],
  target: readonly (readonly [number, number])[],
): readonly number[] | null {
  if (source.length !== 4 || target.length !== 4) return null;

  const a: number[][] = [];
  const b: number[] = [];

  for (let i = 0; i < 4; i += 1) {
    const s = source[i];
    const t = target[i];
    if (s === undefined || t === undefined) return null;
    const [sx, sy] = s;
    const [tx, ty] = t;

    a.push([sx, sy, 1, 0, 0, 0, -sx * tx, -sy * tx]);
    b.push(tx);
    a.push([0, 0, 0, sx, sy, 1, -sx * ty, -sy * ty]);
    b.push(ty);
  }

  // Eliminación con pivoteo parcial.
  for (let col = 0; col < 8; col += 1) {
    let pivot = col;
    for (let row = col + 1; row < 8; row += 1) {
      if (Math.abs(a[row]?.[col] ?? 0) > Math.abs(a[pivot]?.[col] ?? 0)) pivot = row;
    }

    const pivotValue = a[pivot]?.[col] ?? 0;
    if (Math.abs(pivotValue) < 1e-12) return null;

    if (pivot !== col) {
      const rowA = a[col];
      const rowB = a[pivot];
      if (rowA === undefined || rowB === undefined) return null;
      a[col] = rowB;
      a[pivot] = rowA;
      const temp = b[col] ?? 0;
      b[col] = b[pivot] ?? 0;
      b[pivot] = temp;
    }

    const pivotRow = a[col];
    if (pivotRow === undefined) return null;
    const divisor = pivotRow[col] ?? 1;

    for (let row = col + 1; row < 8; row += 1) {
      const current = a[row];
      if (current === undefined) continue;
      const factor = (current[col] ?? 0) / divisor;
      if (factor === 0) continue;
      for (let k = col; k < 8; k += 1) {
        current[k] = (current[k] ?? 0) - factor * (pivotRow[k] ?? 0);
      }
      b[row] = (b[row] ?? 0) - factor * (b[col] ?? 0);
    }
  }

  const solution = new Array<number>(8).fill(0);
  for (let row = 7; row >= 0; row -= 1) {
    const current = a[row];
    if (current === undefined) return null;
    let sum = b[row] ?? 0;
    for (let col = row + 1; col < 8; col += 1) {
      sum -= (current[col] ?? 0) * (solution[col] ?? 0);
    }
    const divisor = current[row] ?? 0;
    if (Math.abs(divisor) < 1e-12) return null;
    solution[row] = sum / divisor;
  }

  return solution;
}

/* ------------------------------------------------------------------ *
 * Medio del marcador (D01, D15)
 * ------------------------------------------------------------------ */

/**
 * URL de la imagen de un marcador, si usa una propia.
 *
 * Los APNG (D15) no necesitan tratamiento especial —el navegador los anima
 * como un PNG cualquiera—, pero sí lo necesita el movimiento reducido: un
 * icono animado en bucle es exactamente lo que la preferencia del sistema pide
 * desactivar, así que se devuelve también si conviene congelarlo.
 */
export function markerMedia(
  hotspot: Hotspot,
  mediaUrls: ReadonlyMap<string, string>,
): { readonly url: string; readonly animated: boolean } | null {
  const geometry = hotspot.geometry;
  if (!('mediaId' in geometry) || geometry.mediaId === null) return null;

  const url = mediaUrls.get(geometry.mediaId);
  if (url === undefined) return null;

  // La extensión es lo único que se tiene sin descargar el archivo. Un APNG se
  // sirve como .png, así que se marca como animado todo lo que pueda serlo y
  // la decisión de congelar se toma arriba, donde se conoce la preferencia.
  const animated = /\.(a?png|gif|webp|avif)$/i.test(url);
  return { url, animated };
}
