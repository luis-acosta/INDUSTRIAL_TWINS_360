describe('shouldPreload', () => {
  // TEST-HSP-013
  it('«al entrar» carga desde el principio', () => {
    const eager = hotspot({ preload: 'eager' });
    expect(shouldPreload(eager, 'sceneEnter')).toBe(true);
  });

  // TEST-HSP-014
  it('«al pasar el puntero» no carga al entrar en la escena', () => {
    // Precargar todo satura la red y retrasa la primera imagen, que es lo
    // único que el visitante está esperando.
    const onHover = hotspot({ preload: 'onHover' });

    expect(shouldPreload(onHover, 'sceneEnter')).toBe(false);
    expect(shouldPreload(onHover, 'hover')).toBe(true);
  });

  // TEST-HSP-015
  it('«al interactuar» espera al clic', () => {
    const lazy = hotspot({ preload: 'lazy' });

    expect(shouldPreload(lazy, 'sceneEnter')).toBe(false);
    expect(shouldPreload(lazy, 'hover')).toBe(false);
    expect(shouldPreload(lazy, 'activate')).toBe(true);
  });
});

