/**
 * Pruebas de la presentación de marcadores.
 *
 * La homografía de la imagen proyectada se comprueba por su efecto y no por sus
 * coeficientes: se aplica la matriz a las cuatro esquinas del rectángulo de
 * origen y se verifica que caen en las cuatro del destino. Es la única forma de
 * que la prueba falle cuando la matriz esté mal, en lugar de limitarse a
 * confirmar que devuelve algo con forma de matriz.
 */
import { describe, expect, it } from 'vitest';
import type { Hotspot, Uv } from '@it360/domain';
import { makeHotspot, testUuid } from '@it360/domain/testing';
import {
  baseSizePx,
  depthScale,
  effectiveScale,
  hasUnresolvedVariables,
  isVisibleOnDevice,
  markerMedia,
  markerTransform,
  pointInPolygon,
  polygonClipPath,
  polygonScreenPoints,
  quadTransform,
  resolveTemplate,
  shouldPreload,
  visibleHotspots,
  type Quad,
} from './hotspot-presentation';

const SCENE = testUuid(1);

function hotspot(overrides: Parameters<typeof makeHotspot>[2] = {}): Hotspot {
  return makeHotspot(1, SCENE, overrides);
}

