describe('visibilidad', () => {
  // TEST-HSP-009
  it('respeta la visibilidad declarada por dispositivo', () => {
    const soloEscritorio = hotspot({
      visibility: { desktop: true, tablet: false, mobile: false, vr: false },
    });

    expect(isVisibleOnDevice(soloEscritorio, 'desktop')).toBe(true);
    expect(isVisibleOnDevice(soloEscritorio, 'mobile')).toBe(false);
    expect(isVisibleOnDevice(soloEscritorio, 'vr')).toBe(false);
  });

  // TEST-HSP-010
  it('no muestra propuestas automáticas sin revisar en el recorrido publicado', () => {
    const propuesta = makeHotspot(2, SCENE, { autoGenerated: true, reviewed: false });
    const normal = makeHotspot(3, SCENE, {});

    const publicado = visibleHotspots([propuesta, normal], 'desktop');
    const enEditor = visibleHotspots([propuesta, normal], 'desktop', { includeUnreviewed: true });

    expect(publicado.map((h) => h.id)).toEqual([normal.id]);
    expect(enEditor).toHaveLength(2);
  });

  // TEST-HSP-011
  it('oculta en el editor lo que el autor marcó como oculto, sin afectar al recorrido', () => {
    const oculto = makeHotspot(4, SCENE, { hiddenInEditor: true });

    expect(visibleHotspots([oculto], 'desktop', { inEditor: true })).toHaveLength(0);
    expect(visibleHotspots([oculto], 'desktop')).toHaveLength(1);
  });

  // TEST-HSP-012
  it('ordena de forma estable', () => {
    // Con un orden inestable, dos marcadores solapados se pulsan uno distinto
    // cada vez que se entra en la escena.
    const a = makeHotspot(5, SCENE, { order: 2 });
    const b = makeHotspot(6, SCENE, { order: 1 });
    const c = makeHotspot(7, SCENE, { order: 1 });

    const first = visibleHotspots([a, b, c], 'desktop').map((h) => h.id);
    const second = visibleHotspots([c, a, b], 'desktop').map((h) => h.id);

    expect(first).toEqual(second);
    expect(first[0]).toBe(b.id < c.id ? b.id : c.id);
  });
});

