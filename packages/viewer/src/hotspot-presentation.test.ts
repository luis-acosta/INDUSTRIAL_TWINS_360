describe('quadTransform', () => {
  /** Aplica una `matrix3d` de CSS a un punto. */
  function apply(matrix: string, x: number, y: number): { x: number; y: number } {
    const values = (matrix.match(/matrix3d\(([^)]+)\)/)?.[1] ?? '')
      .split(',')
      .map((v) => Number(v.trim()));

    // Columna-mayor: m[col * 4 + row].
    const a = values[0] ?? 0;
    const d = values[1] ?? 0;
    const g = values[3] ?? 0;
    const b = values[4] ?? 0;
    const e = values[5] ?? 0;
    const h = values[7] ?? 0;
    const c = values[12] ?? 0;
    const f = values[13] ?? 0;

    const w = g * x + h * y + 1;
    return { x: (a * x + b * y + c) / w, y: (d * x + e * y + f) / w };
  }

  // TEST-HSP-029
  it('lleva las cuatro esquinas del rectángulo a las del cuadrilátero', () => {
    // Es la comprobación que importa: la matriz está bien si su efecto es el
    // pedido, no si tiene forma de matriz.
    const quad: Quad = {
      topLeft: { x: 20, y: 10 },
      topRight: { x: 180, y: 40 },
      bottomRight: { x: 160, y: 140 },
      bottomLeft: { x: 40, y: 120 },
    };

    const matrix = quadTransform(100, 80, quad);
    expect(matrix).not.toBeNull();
    if (matrix === null) return;

    const corners: ReadonlyArray<[number, number, { x: number; y: number }]> = [
      [0, 0, quad.topLeft],
      [100, 0, quad.topRight],
      [100, 80, quad.bottomRight],
      [0, 80, quad.bottomLeft],
    ];

    for (const [x, y, expected] of corners) {
      const got = apply(matrix, x, y);
      expect(got.x).toBeCloseTo(expected.x, 3);
      expect(got.y).toBeCloseTo(expected.y, 3);
    }
  });

  // TEST-HSP-030
  it('un trapecio necesita homografía y no una transformación afín', () => {
    // Si el resultado fuera afín, los coeficientes de perspectiva serían cero
    // y un rectángulo no podría convertirse en trapecio.
    const trapecio: Quad = {
      topLeft: { x: 30, y: 0 },
      topRight: { x: 70, y: 0 },
      bottomRight: { x: 100, y: 100 },
      bottomLeft: { x: 0, y: 100 },
    };

    const matrix = quadTransform(100, 100, trapecio);
    expect(matrix).not.toBeNull();
    if (matrix === null) return;

    const values = (matrix.match(/matrix3d\(([^)]+)\)/)?.[1] ?? '')
      .split(',')
      .map((v) => Number(v.trim()));

    const perspectiva = Math.abs(values[3] ?? 0) + Math.abs(values[7] ?? 0);
    expect(perspectiva).toBeGreaterThan(1e-6);
  });

  // TEST-HSP-031
  it('la identidad sale cuando el destino es el propio rectángulo', () => {
    const matrix = quadTransform(100, 50, {
      topLeft: { x: 0, y: 0 },
      topRight: { x: 100, y: 0 },
      bottomRight: { x: 100, y: 50 },
      bottomLeft: { x: 0, y: 50 },
    });

    expect(matrix).not.toBeNull();
    if (matrix === null) return;
    const got = apply(matrix, 50, 25);
    expect(got.x).toBeCloseTo(50, 6);
    expect(got.y).toBeCloseTo(25, 6);
  });

  // TEST-HSP-032
  it('devuelve null para un cuadrilátero degenerado', () => {
    // Una matriz con infinitos haría que el navegador no dibujara nada sin
    // explicación.
    const colapsado: Quad = {
      topLeft: { x: 10, y: 10 },
      topRight: { x: 10, y: 10 },
      bottomRight: { x: 10, y: 10 },
      bottomLeft: { x: 10, y: 10 },
    };

    expect(quadTransform(100, 100, colapsado)).toBeNull();
  });

  // TEST-HSP-033
  it('devuelve null si el rectángulo de origen no tiene área', () => {
    const quad: Quad = {
      topLeft: { x: 0, y: 0 },
      topRight: { x: 10, y: 0 },
      bottomRight: { x: 10, y: 10 },
      bottomLeft: { x: 0, y: 10 },
    };

    expect(quadTransform(0, 100, quad)).toBeNull();
    expect(quadTransform(100, 0, quad)).toBeNull();
  });

  // TEST-HSP-034
  it('funciona con una esquina en el origen', () => {
    // Sin pivoteo parcial, el pivote sale nulo y la solución lleva infinitos.
    const quad: Quad = {
      topLeft: { x: 0, y: 0 },
      topRight: { x: 120, y: 15 },
      bottomRight: { x: 110, y: 95 },
      bottomLeft: { x: 5, y: 80 },
    };

    const matrix = quadTransform(100, 80, quad);
    expect(matrix).not.toBeNull();
    expect(matrix).not.toContain('NaN');
    expect(matrix).not.toContain('Infinity');
  });
});

