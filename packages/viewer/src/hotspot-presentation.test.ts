describe('markerTransform', () => {
  const identity = { scale: 1, roll: 0, tilt: 0, spin: 0, depth: 1 } as const;

  it('TEST-HPR-041 un marcador sin rotación sólo se centra y se escala', () => {
    const css = markerTransform({ transform: identity, projection: 'billboard', appliedScale: 1 });
    expect(css).toBe('translate(-50%, -50%) scale(1.000)');
  });

  it('TEST-HPR-042 de frente se aplica el giro en el plano de la vista', () => {
    const css = markerTransform({
      transform: { ...identity, roll: Math.PI / 2 },
      projection: 'billboard',
      appliedScale: 1,
    });
    expect(css).toContain('rotateZ(');
  });

  it('TEST-HPR-043 de frente la inclinación y el giro vertical se ignoran', () => {
    // Es la misma regla que la pantalla de autoría le enseña al autor:
    // aplicarlas aquí daría un marcador deformado que contradice lo que la
    // interfaz promete.
    const css = markerTransform({
      transform: { ...identity, tilt: 1, spin: 1 },
      projection: 'billboard',
      appliedScale: 1,
    });
    expect(css).not.toContain('rotateX(');
    expect(css).not.toContain('rotateY(');
  });

  it('TEST-HPR-044 adherido a la escena se aplican los tres ejes', () => {
    const css = markerTransform({
      transform: { ...identity, roll: 0.3, tilt: 0.4, spin: 0.5 },
      projection: 'sticker',
      appliedScale: 1,
    });
    expect(css).toContain('rotateX(');
    expect(css).toContain('rotateY(');
    expect(css).toContain('rotateZ(');
  });

  it('TEST-HPR-045 flotante también usa los tres ejes', () => {
    const css = markerTransform({
      transform: { ...identity, tilt: 0.4 },
      projection: 'floating',
      appliedScale: 1,
    });
    expect(css).toContain('rotateX(');
  });

  it('TEST-HPR-046 la perspectiva sólo se declara si hay rotación fuera del plano', () => {
    // Declararla en todos los marcadores fuerza una capa de composición por
    // marcador, y en una escena con cincuenta se nota.
    const flat = markerTransform({
      transform: { ...identity, roll: 1 },
      projection: 'sticker',
      appliedScale: 1,
    });
    const spatial = markerTransform({
      transform: { ...identity, tilt: 1 },
      projection: 'sticker',
      appliedScale: 1,
    });

    expect(flat).not.toContain('perspective(');
    expect(spatial).toContain('perspective(');
  });

  it('TEST-HPR-047 la escala resuelta se respeta', () => {
    const css = markerTransform({ transform: identity, projection: 'billboard', appliedScale: 2.5 });
    expect(css).toContain('scale(2.500)');
  });

  it('TEST-HPR-048 la profundidad agranda o reduce el marcador', () => {
    const near = markerTransform({
      transform: { ...identity, depth: 4 },
      projection: 'sticker',
      appliedScale: 1,
    });
    const far = markerTransform({
      transform: { ...identity, depth: 0.25 },
      projection: 'sticker',
      appliedScale: 1,
    });

    expect(near).toContain('scale(2.000)');
    expect(far).toContain('scale(0.500)');
  });

  it('TEST-HPR-049 la profundidad máxima no multiplica el marcador por diez', () => {
    // A diez ocuparía más que la pantalla y taparía justo lo que señala.
    expect(depthScale(10)).toBeCloseTo(Math.sqrt(10), 5);
    expect(depthScale(10)).toBeLessThan(4);
  });

  it('TEST-HPR-050 la profundidad fuera de rango se acota', () => {
    expect(depthScale(0)).toBeCloseTo(depthScale(0.1), 5);
    expect(depthScale(1000)).toBeCloseTo(depthScale(10), 5);
  });
});
