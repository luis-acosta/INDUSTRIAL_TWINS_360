describe('effectiveScale', () => {
  // TEST-HSP-016
  it('un marcador adherido escala con la perspectiva', () => {
    const sticker = hotspot({
      style: { ...hotspot().style, projection: 'sticker' },
    });

    expect(effectiveScale({ hotspot: sticker, projectionScale: 0.5, hovered: false })).toBeCloseTo(
      0.5,
      6,
    );
  });

  // TEST-HSP-017
  it('un marcador de frente ignora la perspectiva', () => {
    const billboard = hotspot({ style: { ...hotspot().style, projection: 'billboard' } });

    expect(effectiveScale({ hotspot: billboard, projectionScale: 0.2, hovered: false })).toBe(1);
  });

  // TEST-HSP-018
  it('nunca reduce un marcador adherido hasta hacerlo impulsable', () => {
    // En el borde de una panorámica de campo amplio, la perspectiva lo
    // dejaría en dos píxeles: visible y no pulsable.
    const sticker = hotspot({ style: { ...hotspot().style, projection: 'sticker' } });

    expect(effectiveScale({ hotspot: sticker, projectionScale: 0.01, hovered: false })).toBe(0.35);
  });

  // TEST-HSP-019
  it('acota también el crecimiento', () => {
    const sticker = hotspot({ style: { ...hotspot().style, projection: 'sticker' } });
    expect(effectiveScale({ hotspot: sticker, projectionScale: 50, hovered: false })).toBe(3);
  });

  // TEST-HSP-020
  it('aplica el aumento al pasar el puntero sobre la escala del autor', () => {
    const grande = hotspot({
      style: {
        ...hotspot().style,
        projection: 'billboard',
        transform: { ...hotspot().style.transform, scale: 2 },
        hoverScale: 1.5,
      },
    });

    expect(effectiveScale({ hotspot: grande, projectionScale: 1, hovered: true })).toBeCloseTo(3, 6);
  });
});

