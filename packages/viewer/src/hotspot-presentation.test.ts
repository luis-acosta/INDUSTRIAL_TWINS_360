describe('polígonos', () => {
  const square: readonly Uv[] = [
    { u: 0.4, v: 0.4 },
    { u: 0.6, v: 0.4 },
    { u: 0.6, v: 0.6 },
    { u: 0.4, v: 0.6 },
  ];

  const project = (uv: Uv): { x: number; y: number } => ({ x: uv.u * 1000, y: uv.v * 500 });

  // TEST-HSP-022
  it('proyecta todos los vértices', () => {
    const points = polygonScreenPoints(square, project);

    expect(points).not.toBeNull();
    expect(points).toHaveLength(4);
    expect(points?.[0]).toEqual({ x: 400, y: 200 });
  });

  // TEST-HSP-023
  it('descarta el polígono si un vértice no se puede proyectar', () => {
    // Un vértice detrás de la cámara dibujaría una forma que no corresponde a
    // nada y que capturaría clics donde no debe.
    const parcial = (uv: Uv): { x: number; y: number } | null =>
      uv.u > 0.5 ? null : { x: uv.u * 1000, y: uv.v * 500 };

    expect(polygonScreenPoints(square, parcial)).toBeNull();
  });

  // TEST-HSP-024
  it('el recorte normal es el contorno', () => {
    const points = polygonScreenPoints(square, project) ?? [];
    const clip = polygonClipPath(points);

    expect(clip.startsWith('polygon(')).toBe(true);
    expect(clip).not.toContain('evenodd');
    expect(clip).toContain('400.0px 200.0px');
  });

  // TEST-HSP-025
  it('el polígono invertido activa lo que queda fuera', () => {
    const points = polygonScreenPoints(square, project) ?? [];
    const clip = polygonClipPath(points, { inverted: true, width: 1000, height: 500 });

    expect(clip).toContain('evenodd');
    expect(clip).toContain('0px 0px');
    expect(clip).toContain('1000px 500px');
  });

  // TEST-HSP-026
  it('decide la pertenencia de un punto por geometría y no por el recorte', () => {
    // Con `clip-path`, el área de pulsación de un polígono invertido incluye
    // todo el rectángulo y el visitante lo activaría pulsando en cualquier
    // parte de la pantalla.
    const points = polygonScreenPoints(square, project) ?? [];

    expect(pointInPolygon({ x: 500, y: 250 }, points)).toBe(true);
    expect(pointInPolygon({ x: 100, y: 100 }, points)).toBe(false);
  });

  // TEST-HSP-027
  it('un punto sobre el borde no cuelga el algoritmo', () => {
    const points = polygonScreenPoints(square, project) ?? [];
    expect(typeof pointInPolygon({ x: 400, y: 200 }, points)).toBe('boolean');
  });

  // TEST-HSP-028
  it('reconoce el interior de un polígono cóncavo', () => {
    // Una forma en L: el centro del rectángulo que la envuelve queda fuera.
    const l = [
      { x: 0, y: 0 },
      { x: 100, y: 0 },
      { x: 100, y: 30 },
      { x: 30, y: 30 },
      { x: 30, y: 100 },
      { x: 0, y: 100 },
    ];

    expect(pointInPolygon({ x: 10, y: 10 }, l)).toBe(true);
    expect(pointInPolygon({ x: 70, y: 70 }, l)).toBe(false);
  });
});

