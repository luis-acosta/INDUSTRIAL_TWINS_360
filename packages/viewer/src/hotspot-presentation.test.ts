describe('markerMedia', () => {
  // TEST-HSP-035
  it('devuelve la URL del icono propio', () => {
    const conMedio = hotspot({
      geometry: { shape: 'icon', mediaId: testUuid(9), builtinIcon: 'marker', sizePx: 48 },
    });
    const urls = new Map([[testUuid(9), 'media/flecha.png']]);

    expect(markerMedia(conMedio, urls)?.url).toBe('media/flecha.png');
  });

  // TEST-HSP-036
  it('marca como animable lo que puede estar animado', () => {
    // Un APNG se sirve como .png y no se distingue sin descargarlo; se marca
    // para que la preferencia de movimiento reducido pueda congelarlo.
    const conMedio = hotspot({
      geometry: { shape: 'icon', mediaId: testUuid(9), builtinIcon: 'marker', sizePx: 48 },
    });

    expect(markerMedia(conMedio, new Map([[testUuid(9), 'media/giro.png']]))?.animated).toBe(true);
    expect(markerMedia(conMedio, new Map([[testUuid(9), 'media/fijo.jpg']]))?.animated).toBe(false);
  });

  // TEST-HSP-037
  it('sin medio propio no devuelve nada', () => {
    expect(markerMedia(hotspot(), new Map())).toBeNull();
  });

  // TEST-HSP-038
  it('un medio que falta del paquete no devuelve una URL inventada', () => {
    const conMedio = hotspot({
      geometry: { shape: 'icon', mediaId: testUuid(9), builtinIcon: 'marker', sizePx: 48 },
    });

    expect(markerMedia(conMedio, new Map())).toBeNull();
  });
});

