describe('resolveTemplate', () => {
  const context = {
    scene: { title: 'Sala de bombas', index: 2, total: 7 },
    asset: { tag: 'P-101A', name: 'Bomba principal' },
    score: { total: 80 },
    telemetry: { presion: '5,2 bar' },
    time: { elapsed: '03:14' },
  };

  // TEST-HSP-001
  it('sustituye una variable simple', () => {
    expect(resolveTemplate('{{asset.tag}}', context)).toBe('P-101A');
  });

  // TEST-HSP-002
  it('sustituye varias y conserva el texto de alrededor', () => {
    expect(resolveTemplate('{{asset.tag}} — {{asset.name}}', context)).toBe(
      'P-101A — Bomba principal',
    );
  });

  // TEST-HSP-003
  it('admite espacios dentro de las llaves', () => {
    expect(resolveTemplate('{{  asset.tag  }}', context)).toBe('P-101A');
  });

  // TEST-HSP-004
  it('deja visible la variable que no existe', () => {
    // Borrarla produciría «Presión:  bar» y el autor no sabría por qué.
    const resolved = resolveTemplate('Presión: {{telemetry.caudal}}', context);

    expect(resolved).toBe('Presión: {{telemetry.caudal}}');
    expect(hasUnresolvedVariables(resolved)).toBe(true);
  });

  // TEST-HSP-005
  it('convierte números a texto', () => {
    expect(resolveTemplate('{{scene.index}} de {{scene.total}}', context)).toBe('2 de 7');
    expect(resolveTemplate('Puntos: {{score.total}}', context)).toBe('Puntos: 80');
  });

  // TEST-HSP-006
  it('no resuelve una ruta que atraviesa algo que no es objeto', () => {
    expect(resolveTemplate('{{asset.tag.length}}', context)).toBe('{{asset.tag.length}}');
  });

  // TEST-HSP-007
  it('no evalúa nada: una plantilla no puede ejecutar código', () => {
    // El recorrido publicado es de sólo lectura. Lo único que hace la
    // sustitución es buscar una ruta en un objeto plano.
    const malicioso = '{{constructor.constructor}}';
    expect(resolveTemplate(malicioso, context)).toBe(malicioso);
  });

  // TEST-HSP-008
  it('una plantilla sin variables se devuelve igual', () => {
    expect(resolveTemplate('Bomba principal', context)).toBe('Bomba principal');
  });
});

