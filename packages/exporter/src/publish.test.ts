/**
 * Pruebas de publicación.
 *
 * Lo que se verifica aquí son las reglas que separan «un recorrido que se
 * puede entregar a un cliente» de «un recorrido que no debería haber salido
 * del equipo»: que lo excluido no se publica, que una propuesta automática sin
 * revisar no llega al cliente, que un enlace a una escena ausente no queda
 * como botón muerto, y que ninguna credencial viaja en el paquete.
 *
 * La última es la que justifica el estilo de la prueba: no basta comprobar que
 * el manifiesto no tiene tokens, porque eso también sería cierto si el
 * proyecto de prueba tampoco los tuviera. La prueba comprueba primero que el
 * proyecto **sí** los tiene, y después que el paquete no.
 */
import { describe, expect, it } from 'vitest';
import { unzipSync } from 'fflate';
import {
  FORBIDDEN_MANIFEST_KEYS,
  findForbiddenKeys,
  type Action,
  type Project,
  type Uuid,
} from '@it360/domain';
import { makeHotspot, makeMedia, makeProject, makeScene, testUuid } from '@it360/domain/testing';
import {
  buildSite,
  exportOfflinePackage,
  exportScormPackage,
  exportWebSite,
  planPublication,
  publicationReport,
} from './index';

const encoder = new TextEncoder();
const decoder = new TextDecoder();

/**
 * Deshace el escapado de HTML.
 *
 * Las pruebas de la política de seguridad comparan la política tal como la
 * lee el navegador, no tal como está escrita en el atributo: el valor va
 * escapado a propósito y comprobar la forma escapada ataría la prueba a un
 * detalle de representación.
 */
function unescapeHtml(text: string): string {
  return text
    .replace(/&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&');
}

const RUNTIME = new Map<string, Uint8Array>([
  ['viewer/app.js', encoder.encode('/* visor */')],
  ['viewer/app.css', encoder.encode('.it-viewer{}')],
]);

const PROJECT_ID = testUuid(1);

/** Acción de navegación hacia otra escena. */
function goToScene(n: number, target: Uuid): Action {
  return {
    id: testUuid(n),
    event: 'click',
    config: {
      type: 'goToScene',
      sceneId: target,
      entryMode: 'smart',
      transition: { kind: 'fade', durationMs: 400, useGeometry: false },
    },
    order: 0,
    delayMs: 0,
    focusDwellMs: 1200,
    once: false,
    requiresScore: null,
    enabled: true,
  };
}

/** Proyecto de prueba con dos escenas, medios y una conexión con credencial. */
function projectFixture(overrides: Partial<Project> = {}): Project {
  const mediaA = makeMedia(1, { relativePath: 'media/escena-1.jpg' });
  const mediaB = makeMedia(2, { relativePath: 'media/escena-2.jpg' });

  const sceneA = makeScene(11, PROJECT_ID, {
    title: 'Sala de bombas',
    mediaId: mediaA.id,
    hotspots: [
      makeHotspot(21, testUuid(11), {
        name: 'A la plataforma',
        actions: [goToScene(31, testUuid(12))],
      }),
    ],
  });

  const sceneB = makeScene(12, PROJECT_ID, { title: 'Plataforma superior', mediaId: mediaB.id });

  return makeProject({
    id: PROJECT_ID,
    media: [mediaA, mediaB],
    scenes: [sceneA, sceneB],
    settings: {
      ...makeProject({}).settings,
      entrySceneId: sceneA.id,
    },
    telemetryConnections: [
      {
        id: testUuid(9),
        name: 'Historiador de planta',
        url: 'https://influx.planta.local:8086',
        org: 'planta-norte',
        bucket: 'proceso',
        tokenRef: { keyId: 'influx-lectura', label: 'Token de lectura' },
        timeoutMs: 8000,
        verifyTls: true,
        tlsExemptionReason: '',
        enabled: true,
      },
    ],
    ...overrides,
  });
}

const SITE_OPTIONS = {
  publishedAt: '2026-03-01T10:00:00.000Z',
  appVersion: '0.14.0',
  runtime: RUNTIME,
  mediaFiles: new Map([
    ['media/escena-1.jpg', encoder.encode('imagen-1')],
    ['media/escena-2.jpg', encoder.encode('imagen-2')],
  ]),
};

describe('planPublication', () => {
  // TEST-PUB-001
  it('publica las escenas incluidas y deja fuera las excluidas', () => {
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 1 ? { ...scene, excludedFromPublish: true } : scene,
    );
    const plan = planPublication({ ...base, scenes });

    expect(plan.counts.scenes).toBe(1);
    expect(plan.counts.scenesExcluded).toBe(1);
    expect(plan.warnings.some((w) => w.reason === 'sceneExcluded')).toBe(true);
  });

  // TEST-PUB-002
  it('no publica una propuesta automática sin revisar', () => {
    const base = projectFixture();
    const firstScene = base.scenes[0];
    expect(firstScene).toBeDefined();
    const scenes = [
      {
        ...(firstScene as NonNullable<typeof firstScene>),
        hotspots: [
          makeHotspot(25, testUuid(11), {
            name: 'Propuesta',
            autoGenerated: true,
            reviewed: false,
            actions: [],
          }),
        ],
      },
      ...base.scenes.slice(1),
    ];

    const plan = planPublication({ ...base, scenes });

    expect(plan.counts.hotspots).toBe(0);
    expect(plan.counts.hotspotsExcluded).toBe(1);
    expect(plan.warnings.some((w) => w.reason === 'unreviewedProposal')).toBe(true);
  });

  // TEST-PUB-003
  it('publica la propuesta sin revisar sólo si se pide explícitamente', () => {
    const base = projectFixture();
    const firstScene = base.scenes[0];
    const scenes = [
      {
        ...(firstScene as NonNullable<typeof firstScene>),
        hotspots: [
          makeHotspot(25, testUuid(11), { autoGenerated: true, reviewed: false, actions: [] }),
        ],
      },
      ...base.scenes.slice(1),
    ];

    const plan = planPublication({ ...base, scenes }, { includeUnreviewed: true });
    expect(plan.counts.hotspots).toBe(1);
  });

  // TEST-PUB-004
  it('retira la acción que lleva a una escena no publicada', () => {
    // El marcador se queda: lo que desaparece es el enlace que no lleva a
    // ninguna parte. Un botón que no hace nada es peor que no tenerlo.
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 1 ? { ...scene, excludedFromPublish: true } : scene,
    );

    const plan = planPublication({ ...base, scenes });

    expect(plan.counts.hotspots).toBe(1);
    expect(plan.counts.actionsNeutralized).toBe(1);
    expect(plan.scenes[0]?.hotspots[0]?.actions).toHaveLength(0);
    expect(plan.warnings.some((w) => w.reason === 'danglingTarget')).toBe(true);
  });

  // TEST-PUB-005
  it('no publica una escena sin imagen', () => {
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 0 ? { ...scene, mediaId: null } : scene,
    );

    const plan = planPublication({ ...base, scenes });

    expect(plan.counts.scenes).toBe(1);
    expect(plan.warnings.some((w) => w.reason === 'missingMedia')).toBe(true);
  });

  // TEST-PUB-006
  it('no copia un archivo en cuarentena', () => {
    // Un archivo que no pasó la validación al importarse no se pone en el
    // navegador del cliente por el hecho de publicar.
    const base = projectFixture();
    const media = base.media.map((m, index) =>
      index === 0 ? { ...m, quarantined: true, quarantineReason: 'tipo MIME no coincide' } : m,
    );

    const plan = planPublication({ ...base, media });

    expect(plan.media.some((m) => m.quarantined)).toBe(false);
    expect(plan.warnings.some((w) => w.message.includes('cuarentena'))).toBe(true);
  });

  // TEST-PUB-007
  it('reemplaza una escena de entrada que no se publica', () => {
    // Dejar el identificador original haría que el visor abriera en una
    // escena que no existe en el paquete: pantalla negra al abrir.
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 0 ? { ...scene, excludedFromPublish: true } : scene,
    );

    const plan = planPublication({ ...base, scenes });

    expect(plan.entrySceneId).not.toBe(base.settings.entrySceneId);
    expect(plan.scenes.some((s) => s.id === plan.entrySceneId)).toBe(true);
  });

  // TEST-PUB-008
  it('no publica un marcador oculto en todos los dispositivos', () => {
    const base = projectFixture();
    const firstScene = base.scenes[0];
    const scenes = [
      {
        ...(firstScene as NonNullable<typeof firstScene>),
        hotspots: [
          makeHotspot(26, testUuid(11), {
            actions: [],
            visibility: { desktop: false, tablet: false, mobile: false, vr: false },
          }),
        ],
      },
      ...base.scenes.slice(1),
    ];

    const plan = planPublication({ ...base, scenes });

    expect(plan.counts.hotspots).toBe(0);
    expect(plan.warnings.some((w) => w.reason === 'hiddenInAllDevices')).toBe(true);
  });
});

describe('buildSite', () => {
  // TEST-PUB-009
  it('produce índice, manifiesto, visor y medios con rutas relativas', () => {
    const site = buildSite(projectFixture(), SITE_OPTIONS);
    const paths = site.files.map((f) => f.path);

    expect(paths).toContain('index.html');
    expect(paths).toContain('manifiesto.json');
    expect(paths).toContain('viewer/app.js');
    expect(paths).toContain('media/escena-1.jpg');

    const html = decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes);
    // Rutas relativas: una publicación en subcarpeta de intranet es el caso
    // habitual y las rutas absolutas la rompen.
    expect(html).toContain('src="./viewer/app.js"');
    expect(html).not.toContain('src="/viewer');
  });

  // TEST-PUB-010
  it('el paquete no contiene credenciales aunque el proyecto sí las tenga', () => {
    const project = projectFixture();

    // Primero: el proyecto de prueba tiene de verdad lo que no debe salir.
    // Sin esta comprobación, la siguiente pasaría también con un proyecto
    // vacío y no demostraría nada.
    const inProject = findForbiddenKeys(project);
    expect(inProject.length).toBeGreaterThan(0);
    expect(FORBIDDEN_MANIFEST_KEYS.some((key) => inProject.some((path) => path.includes(key)))).toBe(
      true,
    );

    const site = buildSite(project, SITE_OPTIONS);

    expect(findForbiddenKeys(site.manifest)).toEqual([]);
    const manifestText = decoder.decode(
      site.files.find((f) => f.path === 'manifiesto.json')?.bytes,
    );
    expect(manifestText).not.toContain('influx-lectura');
    expect(manifestText).not.toContain('influx.planta.local');
  });

  // TEST-PUB-011
  it('declara una política de seguridad restrictiva', () => {
    const site = buildSite(projectFixture(), SITE_OPTIONS);
    const html = unescapeHtml(
      decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes),
    );

    expect(html).toContain("default-src 'self'");
    expect(html).toContain("object-src 'none'");
    // `frame-src` queda en `self`, que es lo justo para mostrar un PDF del
    // propio paquete dentro del recorrido. Sin orígenes de terceros, porque
    // este proyecto no declara ningún Webframe.
    expect(html).toContain("frame-src 'self'");
    expect(html).not.toMatch(/frame-src[^;]*https?:/);
    expect(html).not.toMatch(/frame-src[^;]*\*/);
    // Sin `unsafe-eval`: el recorrido publicado es contenido estático.
    expect(html).not.toContain('unsafe-eval');
  });

  // TEST-PUB-011b
  it('admite en la política sólo los orígenes de Webframe que el autor declaró', () => {
    // La alternativa fácil habría sido `frame-src *`, que convertiría cada
    // marco en una ventana a la que nadie ha dado el visto bueno, y además lo
    // haría también en los recorridos que no usan ninguno.
    const site = buildSite(projectFixture(), {
      ...SITE_OPTIONS,
      frameOrigins: ['https://scada.planta.local'],
    });
    const html = unescapeHtml(
      decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes),
    );

    expect(html).toContain("frame-src 'self' https://scada.planta.local");
    expect(html).not.toMatch(/frame-src[^;]*\*/);
  });

  // TEST-PUB-012
  it('permite conectar con el servicio de telemetría sólo cuando se declara', () => {
    const withTelemetry = buildSite(projectFixture(), {
      ...SITE_OPTIONS,
      telemetryEndpoint: 'https://telemetria.planta.local',
    });
    const without = buildSite(projectFixture(), SITE_OPTIONS);

    expect(
      unescapeHtml(decoder.decode(withTelemetry.files.find((f) => f.path === 'index.html')?.bytes)),
    ).toContain("connect-src 'self' https://telemetria.planta.local");
    expect(
      unescapeHtml(decoder.decode(without.files.find((f) => f.path === 'index.html')?.bytes)),
    ).toContain("connect-src 'self'");
  });

  // TEST-PUB-013
  it('avisa cuando falta el contenido de un medio en lugar de escribir un archivo vacío', () => {
    const site = buildSite(projectFixture(), {
      ...SITE_OPTIONS,
      mediaFiles: new Map([['media/escena-1.jpg', encoder.encode('imagen-1')]]),
    });

    expect(site.files.some((f) => f.path === 'media/escena-2.jpg')).toBe(false);
    expect(site.warnings.some((w) => w.includes('Falta el contenido'))).toBe(true);
  });

  // TEST-PUB-014
  it('avisa cuando el visor no trae JavaScript', () => {
    // Sin esto, el sitio generado sería una página en blanco y el error
    // aparecería en casa del cliente.
    const site = buildSite(projectFixture(), { ...SITE_OPTIONS, runtime: new Map() });
    expect(site.warnings.some((w) => w.includes('no mostrará el recorrido'))).toBe(true);
  });

  // TEST-PUB-015
  it('escapa el título del proyecto en el HTML', () => {
    const project = projectFixture({ title: 'Planta <script>alert(1)</script>' });
    const site = buildSite(project, SITE_OPTIONS);
    const html = decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes);

    expect(html).not.toContain('<script>alert(1)</script>');
    expect(html).toContain('&lt;script&gt;alert(1)&lt;/script&gt;');
  });

  // TEST-PUB-027
  it('declara un icono vacío cuando el proyecto no tiene marca propia', () => {
    // Sin declaración, el navegador pide /favicon.ico y deja un 404 en el
    // registro del servidor del cliente por cada visita.
    const site = buildSite(projectFixture(), SITE_OPTIONS);
    const html = decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes);

    expect(html).toContain('<link rel="icon" href="data:," />');
  });

  // TEST-PUB-026
  it('una marca propia vacía no deja la pestaña sin título', () => {
    // La cadena vacía no es «sin valor» para `??`: sin comprobar el contenido,
    // el título de la pestaña acababa vacío en todos los proyectos sin marca.
    const site = buildSite(projectFixture({ title: 'Unidad U-200' }), SITE_OPTIONS);
    const html = decoder.decode(site.files.find((f) => f.path === 'index.html')?.bytes);

    expect(html).toContain('<title>Unidad U-200</title>');
  });

  // TEST-PUB-016
  it('el manifiesto refleja el plan y no el proyecto completo', () => {
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 1 ? { ...scene, excludedFromPublish: true } : scene,
    );
    const site = buildSite({ ...base, scenes }, SITE_OPTIONS);

    expect(site.manifest.scenes).toHaveLength(1);
    // La acción retirada por el plan tampoco aparece en el manifiesto.
    expect(site.manifest.scenes[0]?.hotspots[0]?.actions).toHaveLength(0);
  });
});

describe('exportWebSite', () => {
  // TEST-PUB-017
  it('añade el archivo de sumas de verificación', async () => {
    const result = await exportWebSite(projectFixture(), SITE_OPTIONS);
    const sums = decoder.decode(result.files.find((f) => f.path === 'SUMAS.txt')?.bytes);

    expect(sums).toContain('manifiesto.json');
    expect(sums).toMatch(/^[0-9a-f]{64} {2}/m);
    expect(result.checksums.get('index.html')).toMatch(/^[0-9a-f]{64}$/);
  });

  // TEST-PUB-018
  it('no produce un archivo único: el destino es una carpeta', async () => {
    const result = await exportWebSite(projectFixture(), SITE_OPTIONS);
    expect(result.archive).toBeNull();
  });
});

describe('exportOfflinePackage', () => {
  // TEST-PUB-019
  it('produce un ZIP con todo bajo una carpeta raíz', async () => {
    const result = await exportOfflinePackage(projectFixture(), SITE_OPTIONS);
    expect(result.archive).not.toBeNull();

    const entries = Object.keys(unzipSync(result.archive as Uint8Array));
    expect(entries.every((path) => path.startsWith('recorrido/'))).toBe(true);
    expect(entries).toContain('recorrido/index.html');
    expect(entries).toContain('recorrido/LEEME.txt');
  });

  // TEST-PUB-020
  it('se marca como apto para uso sin conexión', async () => {
    const result = await exportOfflinePackage(projectFixture(), SITE_OPTIONS);
    expect(result.manifest.offlineCapable).toBe(true);
  });

  // TEST-PUB-021
  it('el archivo LEEME advierte de que los datos de proceso no son actuales', async () => {
    // «Datos offline se etiquetan como caché, no como telemetría actual»: en
    // un paquete que viaja en USB, el aviso tiene que estar escrito.
    const result = await exportOfflinePackage(projectFixture(), SITE_OPTIONS);
    const zip = unzipSync(result.archive as Uint8Array);
    const readme = decoder.decode(zip['recorrido/LEEME.txt']);

    expect(readme).toContain('no son lecturas actuales');
    expect(readme).toContain('no se conecta al historiador');
  });
});

describe('exportScormPackage', () => {
  // TEST-PUB-022
  it('produce un imsmanifest 1.2 válido en lo esencial', async () => {
    const result = await exportScormPackage(projectFixture(), {
      ...SITE_OPTIONS,
      courseId: 'IT360-U200',
      courseTitle: 'Recorrido de la unidad U-200',
      masteryScore: 75,
    });

    const zip = unzipSync(result.archive as Uint8Array);
    const manifest = decoder.decode(zip['imsmanifest.xml']);

    expect(manifest).toContain('<schemaversion>1.2</schemaversion>');
    expect(manifest).toContain('identifier="IT360-U200"');
    expect(manifest).toContain('<adlcp:masteryscore>75</adlcp:masteryscore>');
    expect(manifest).toContain('adlcp:scormtype="sco" href="index.html"');
    // Cada archivo del paquete se declara: un LMS que no los ve no los sirve.
    expect(manifest).toContain('<file href="viewer/app.js" />');
  });

  // TEST-PUB-023
  it('escapa el título del curso en el XML', async () => {
    const result = await exportScormPackage(projectFixture(), {
      ...SITE_OPTIONS,
      courseId: 'curso-1',
      courseTitle: 'Bombas & válvulas <P-101>',
    });

    const zip = unzipSync(result.archive as Uint8Array);
    const manifest = decoder.decode(zip['imsmanifest.xml']);

    expect(manifest).toContain('Bombas &amp; válvulas &lt;P-101&gt;');
  });
});

describe('publicationReport', () => {
  // TEST-PUB-024
  it('escribe qué se publicó, qué no y por qué', async () => {
    const base = projectFixture();
    const scenes = base.scenes.map((scene, index) =>
      index === 1 ? { ...scene, excludedFromPublish: true } : scene,
    );
    const project = { ...base, scenes };
    const result = await exportWebSite(project, SITE_OPTIONS);
    const report = publicationReport(result, project);

    expect(report).toContain('Escenas: 1 (excluidas: 1)');
    expect(report).toContain('Advertencias');
    expect(report).toContain('está excluida de la publicación');
    expect(report).toContain('No contiene tokens');
  });

  // TEST-PUB-025
  it('dice explícitamente que no hay advertencias cuando no las hay', async () => {
    const result = await exportWebSite(projectFixture(), SITE_OPTIONS);
    const report = publicationReport(result, projectFixture());

    expect(report).toContain('Sin advertencias.');
  });
});
