/**
 * Plan de publicación.
 *
 * Decide qué entra en el paquete publicado y qué se queda fuera, antes de
 * escribir un solo byte. Separarlo de la escritura tiene un motivo práctico:
 * el usuario tiene derecho a ver qué va a publicar —cuántas escenas, qué
 * medios, qué se excluye y por qué— sin esperar a que se generen cientos de
 * megas de imágenes, y la interfaz necesita esa información para la
 * comprobación previa.
 *
 * Las reglas de exclusión no son configurables porque no son preferencias:
 *
 *  - Una escena marcada como excluida no se publica, y con ella se van sus
 *    marcadores. Lo contrario convertiría la casilla en decorativa.
 *  - Un marcador generado automáticamente y sin revisar no se publica. El
 *    plan lo exige con nombre y apellidos: lo que produce un algoritmo
 *    experimental no sale a un cliente sin que una persona lo confirme.
 *  - Un marcador cuya acción apunta a una escena que no se publica se
 *    publica igualmente, pero la acción se neutraliza y queda un aviso. La
 *    alternativa —dejar el enlace roto— produce un recorrido donde pulsar
 *    una flecha no hace nada, que es el peor resultado posible: el usuario no
 *    sabe si falló él, la red o el recorrido.
 *  - Nada relacionado con credenciales, usuarios, permisos o auditoría entra
 *    en el paquete. Eso lo garantiza el manifiesto del dominio, y aquí se
 *    vuelve a comprobar sobre el resultado final.
 */
import {
  FORBIDDEN_MANIFEST_KEYS,
  findForbiddenKeys,
  type Action,
  type Hotspot,
  type Media,
  type Project,
  type Scene,
  type Uuid,
} from '@it360/domain';

/** Motivo por el que algo no se publica o se publica modificado. */
export type ExclusionReason =
  | 'sceneExcluded'
  | 'unreviewedProposal'
  | 'missingMedia'
  | 'danglingTarget'
  | 'hiddenInAllDevices'
  | 'scriptingDisabled';

export interface PlanWarning {
  readonly reason: ExclusionReason;
  /** Tipo de entidad afectada: `scene`, `hotspot`, `action`, `media`. */
  readonly entity: string;
  readonly entityId: string;
  /** Texto para el informe de publicación, en español. */
  readonly message: string;
}

export interface PublishPlan {
  readonly scenes: readonly Scene[];
  /** Medios que hay que copiar, por identificador. */
  readonly media: readonly Media[];
  readonly entrySceneId: string | null;
  readonly warnings: readonly PlanWarning[];
  /** Bytes estimados del contenido original, antes de recomprimir. */
  readonly sourceBytes: number;
  readonly counts: {
    readonly scenes: number;
    readonly scenesExcluded: number;
    readonly hotspots: number;
    readonly hotspotsExcluded: number;
    readonly actionsNeutralized: number;
    readonly media: number;
    readonly assets: number;
    readonly documents: number;
  };
}

export interface PlanOptions {
  /**
   * Incluye los marcadores automáticos sin revisar.
   *
   * Existe para una sola situación: que el autor quiera publicar un borrador
   * interno para revisarlo en equipo. No es el camino por defecto y el
   * informe de publicación lo deja escrito.
   */
  readonly includeUnreviewed?: boolean;
  /** Incluye documentos técnicos en el paquete. */
  readonly includeDocuments?: boolean;
}

/**
 * Acciones que llevan a otra escena y, por tanto, pueden quedar colgando.
 *
 * Se enumeran en lugar de comprobar la presencia del campo `sceneId` para que
 * añadir un tipo de acción nuevo con destino obligue a tocar esta lista: un
 * `in` silencioso dejaría pasar el caso nuevo sin que nadie se enterase.
 */
const SCENE_TARGET_ACTIONS = new Set(['goToScene', 'showPlan']);

function actionTargetScene(action: Action): Uuid | null {
  const config = action.config;
  if (!SCENE_TARGET_ACTIONS.has(config.type)) return null;
  if (config.type === 'goToScene') return config.sceneId;
  return null;
}

/** Decide si un marcador se publica, y por qué no si no se publica. */
function hotspotExclusion(
  hotspot: Hotspot,
  options: PlanOptions,
): ExclusionReason | null {
  if (hotspot.autoGenerated && !hotspot.reviewed && options.includeUnreviewed !== true) {
    return 'unreviewedProposal';
  }
  const visibility = hotspot.visibility;
  if (!visibility.desktop && !visibility.tablet && !visibility.mobile && !visibility.vr) {
    // Oculto en los cuatro dispositivos: publicarlo añade peso al manifiesto y
    // no lo verá nadie nunca.
    return 'hiddenInAllDevices';
  }
  return null;
}

export function planPublication(project: Project, options: PlanOptions = {}): PublishPlan {
  const warnings: PlanWarning[] = [];
  const mediaById = new Map(project.media.map((m) => [m.id, m]));

  const publishable = project.scenes.filter((scene) => {
    if (scene.excludedFromPublish) {
      warnings.push({
        reason: 'sceneExcluded',
        entity: 'scene',
        entityId: scene.id,
        message: `La escena «${scene.title}» está excluida de la publicación.`,
      });
      return false;
    }
    if (scene.kind === 'panorama' && (scene.mediaId === null || !mediaById.has(scene.mediaId))) {
      warnings.push({
        reason: 'missingMedia',
        entity: 'scene',
        entityId: scene.id,
        message: `La escena «${scene.title}» no tiene imagen y no se puede publicar.`,
      });
      return false;
    }
    return true;
  });

  const publishedIds = new Set<Uuid>(publishable.map((scene) => scene.id));

  let hotspotsExcluded = 0;
  let actionsNeutralized = 0;

  const scenes = publishable.map<Scene>((scene) => {
    const hotspots: Hotspot[] = [];

    for (const hotspot of scene.hotspots) {
      const exclusion = hotspotExclusion(hotspot, options);
      if (exclusion !== null) {
        hotspotsExcluded += 1;
        warnings.push({
          reason: exclusion,
          entity: 'hotspot',
          entityId: hotspot.id,
          message:
            exclusion === 'unreviewedProposal'
              ? `El marcador «${hotspot.name}» es una propuesta automática sin revisar y no se publica.`
              : `El marcador «${hotspot.name}» está oculto en todos los dispositivos y no se publica.`,
        });
        continue;
      }

      const actions = hotspot.actions.filter((action) => {
        const target = actionTargetScene(action);
        if (target !== null && !publishedIds.has(target)) {
          actionsNeutralized += 1;
          warnings.push({
            reason: 'danglingTarget',
            entity: 'action',
            entityId: action.id,
            message: `Una acción del marcador «${hotspot.name}» llevaba a una escena que no se publica; se ha retirado para no dejar un enlace que no hace nada.`,
          });
          return false;
        }
        if (action.config.type === 'runScript') {
          const scripting = project.settings.scripting;
          if (scripting.mode === 'disabled' || !scripting.allowInPublished) {
            warnings.push({
              reason: 'scriptingDisabled',
              entity: 'action',
              entityId: action.id,
              message: `Una acción del marcador «${hotspot.name}» ejecuta un guion y la política del proyecto no lo permite en el paquete publicado; se ha retirado.`,
            });
            return false;
          }
        }
        return true;
      });

      hotspots.push(actions.length === hotspot.actions.length ? hotspot : { ...hotspot, actions });
    }

    return { ...scene, hotspots };
  });

  /* --- Medios necesarios --- */

  const needed = new Set<Uuid>();
  for (const scene of scenes) {
    if (scene.mediaId !== null) needed.add(scene.mediaId);
    for (const hotspot of scene.hotspots) {
      // La geometría sólo referencia un medio en las formas que dibujan una
      // imagen; `in` discrimina sin enumerar las seis variantes.
      const geometry = hotspot.geometry;
      if ('mediaId' in geometry && geometry.mediaId !== null) needed.add(geometry.mediaId);
      for (const action of hotspot.actions) {
        const config = action.config;
        if ('mediaId' in config && config.mediaId != null) needed.add(config.mediaId);
      }
    }
  }
  for (const plan of project.plans) needed.add(plan.mediaId);
  if (project.settings.branding.logoMediaId !== null) needed.add(project.settings.branding.logoMediaId);
  if (project.settings.branding.faviconMediaId !== null)
    needed.add(project.settings.branding.faviconMediaId);

  const documents = options.includeDocuments === true ? project.documents : [];
  for (const document of documents) needed.add(document.mediaId);

  const media: Media[] = [];
  for (const id of needed) {
    const found = mediaById.get(id);
    if (found === undefined) {
      warnings.push({
        reason: 'missingMedia',
        entity: 'media',
        entityId: id,
        message: 'Un medio referenciado no existe en el proyecto y no se puede copiar al paquete.',
      });
      continue;
    }
    if (found.quarantined) {
      // Un archivo en cuarentena no pasó la validación al importarse. Copiarlo
      // al paquete lo pondría en el navegador del cliente.
      warnings.push({
        reason: 'missingMedia',
        entity: 'media',
        entityId: id,
        message: `El archivo «${found.originalName}» está en cuarentena (${found.quarantineReason ?? 'sin motivo registrado'}) y no se publica.`,
      });
      continue;
    }
    media.push(found);
  }

  const entry = project.settings.entrySceneId;
  const entrySceneId =
    entry !== null && publishedIds.has(entry) ? entry : (scenes[0]?.id ?? null);

  const referencedAssets = new Set<Uuid>();
  for (const scene of scenes) {
    for (const hotspot of scene.hotspots) {
      if (hotspot.assetId !== null) referencedAssets.add(hotspot.assetId);
    }
  }

  return {
    scenes,
    media,
    entrySceneId,
    warnings,
    sourceBytes: media.reduce((total, m) => total + m.byteSize, 0),
    counts: {
      scenes: scenes.length,
      scenesExcluded: project.scenes.length - scenes.length,
      hotspots: scenes.reduce((total, s) => total + s.hotspots.length, 0),
      hotspotsExcluded,
      actionsNeutralized,
      media: media.length,
      assets: referencedAssets.size,
      documents: documents.length,
    },
  };
}

/**
 * Comprueba que un objeto que va al paquete no lleva claves prohibidas.
 *
 * Se aplica al resultado final y no sólo al manifiesto, porque el manifiesto
 * es una parte del paquete y la lista de claves prohibidas vale para todo lo
 * que se escribe. Devuelve las rutas encontradas para que el informe diga
 * dónde está el problema en lugar de sólo que existe.
 */
export function auditForSecrets(value: unknown): readonly string[] {
  return findForbiddenKeys(value);
}

export { FORBIDDEN_MANIFEST_KEYS };
