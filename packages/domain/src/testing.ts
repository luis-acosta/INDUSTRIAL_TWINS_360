/**
 * Proyecto completo y coherente: dos escenas enlazadas, un activo con
 * documento y telemetría, un plano con su punto navegable y una nota.
 *
 * Es el escenario que usan las pruebas de integridad, de publicación y de
 * persistencia, para que todas trabajen sobre la misma forma de proyecto y un
 * cambio en el modelo rompa un único sitio.
 */
export function makeFullProject(): Project {
  const projectId = testUuid(1);

  const panoramaA = makeMedia(10, { relativePath: 'media/pano-a.jpg' });
  const panoramaB = makeMedia(11, { relativePath: 'media/pano-b.jpg' });
  const planImage = makeMedia(12, {
    mime: 'image/png',
    relativePath: 'media/plano-n0.png',
    width: 2000,
    height: 1400,
    panorama: null,
  });
  const datasheet = makeMedia(13, {
    mime: 'application/pdf',
    kind: 'document',
    relativePath: 'documents/eq-001-ds.pdf',
    width: null,
    height: null,
    panorama: null,
    thumbnailPath: null,
  });

  const assetClass = makeAssetClass(20, { code: 'PUMP_CENTRIFUGAL', name: 'Bomba centrífuga' });
  const plantClass = makeAssetClass(21, { code: 'PLANT', name: 'Planta', level: 'plant' });
  const plant = makeAsset(30, projectId, plantClass.id, {
    tag: 'PL-NORTE' as Asset['tag'],
    name: 'Planta Norte',
    level: 'plant',
  });
  const pump = makeAsset(31, projectId, assetClass.id, {
    tag: 'P-101A' as Asset['tag'],
    name: 'Bomba de alimentación',
    parentId: plant.id,
  });

  const sceneA = makeScene(40, projectId, { title: 'Sala de bombas', mediaId: panoramaA.id });
  const sceneB = makeScene(41, projectId, { title: 'Plataforma superior', mediaId: panoramaB.id });

  const navHotspot = makeHotspot(50, sceneA.id, {
    name: 'A plataforma superior',
    actions: [
      {
        id: testUuid(60) as never,
        event: 'click',
        config: {
          type: 'goToScene',
          sceneId: sceneB.id as never,
          entryMode: 'smart',
          transition: { kind: 'fade', durationMs: 700, useGeometry: false },
        },
        order: 0,
        delayMs: 0,
        focusDwellMs: 1200,
        once: false,
        requiresScore: null,
        enabled: true,
      },
    ] as never,
  });

  const assetHotspot = makeHotspot(51, sceneA.id, {
    name: 'P-101A',
    assetId: pump.id,
    anchor: makeAnchor(0.8, -0.1),
  });

  const connection = makeConnection(70);
  const mapping = makeMapping(71, connection.id, pump.id, {
    variable: 'Presión de descarga',
    measurement: 'presion',
    field: 'value',
    unit: 'bar',
  });

  const plan = makePlan(80, planImage.id);

  /* Una ventana con dos pestañas y bloques de varios tipos: así el viaje de
     ida y vuelta por la base de datos cubre el árbol completo, que es donde
     una pestaña perdida pasaría inadvertida. */
  const infoWindow = createInfoWindow('Ficha de la bomba', testUuid(101), testUuid(100), {
    modal: false,
  });

  return makeProject({
    media: [panoramaA, panoramaB, planImage, datasheet],
    assetClasses: [plantClass, assetClass],
    assets: [plant, pump],
    assetLocations: [makeAssetLocation(90, pump.id, sceneA.id, { hotspotId: assetHotspot.id })],
    documents: [makeDocument(91, datasheet.id, { assetId: pump.id, title: 'Hoja de datos P-101A' })],
    scenes: [
      { ...sceneA, hotspots: [navHotspot, assetHotspot] },
      sceneB,
    ],
    plans: [plan],
    planMarkers: [makePlanMarker(92, plan.id, sceneA.id)],
    telemetryConnections: [connection],
    telemetryMappings: [mapping],
    conditionRules: [makeConditionRule(93, mapping.id, { label: 'Presión alta', threshold: 12 })],
    notes: [makeNote(94, projectId, { sceneId: sceneA.id, assetId: pump.id, categoryId: 'maintenance' })],
    noteCategories: [{ id: 'maintenance', label: 'Mantenimiento', colorToken: 'warning', description: '' }],
    infoWindows: [
      {
        ...infoWindow,
        tabs: [
          {
            id: testUuid(101),
            title: 'General',
            blocks: [
              { type: 'text', text: 'Bomba **P-101A** de la {{scene.title}}.' },
              { type: 'image', mediaId: planImage.id, caption: 'Ubicación' },
            ],
          },
          {
            id: testUuid(102),
            title: 'Documentos',
            blocks: [{ type: 'document', documentId: testUuid(91), page: 1 }],
          },
        ],
      },
    ],
    skins: [makeSkin(95)],
    tours: [makeTour(96, projectId)],
    quizzes: [makeQuiz(97, projectId)],
    users: [makeUser('u-ana')],
    grants: [makeGrant(98, 'u-ana')],
    auditLog: [makeAuditEvent(99)],
    settings: {
      ...makeProject().settings,
      entrySceneId: sceneA.id,
      defaultSkinId: testUuid(95) as never,
    },
  });
}
