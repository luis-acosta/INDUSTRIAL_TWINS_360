export const ISO_NOW = '2026-11-12T19:00:00.000Z';

/**
 * UUID determinista a partir de un número: hace legibles los fallos.
 *
 * Devuelve el tipo marcado `Uuid` y no `string` para que las pruebas usen la
 * misma disciplina de tipos que el producto. Si devolviera `string`, cada
 * prueba tendría que forzar el tipo con un `as`, y esos `as` esconderían un
 * día un identificador mal construido.
 */
export function testUuid(n: number): Uuid {
  return `00000000-0000-4000-8000-${String(n).padStart(12, '0')}` as Uuid;
}

type Partialize<T> = { [K in keyof T]?: T[K] };

