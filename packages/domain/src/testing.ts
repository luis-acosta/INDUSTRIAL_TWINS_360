/**
 * Constructores de datos para pruebas.
 *
 * No se exporta desde `index.ts` a propósito: se consume por la ruta
 * `@it360/domain/testing`, de modo que ningún paquete de producción lo
 * arrastre al paquete final por descuido.
 *
 * El criterio de estos constructores es «válido por defecto, modificable en
 * lo que importa»: cada uno devuelve una entidad que pasa su esquema y su
 * comprobación de integridad, y acepta un objeto parcial para alterar
 * únicamente el campo que la prueba está examinando. Sin esto, cada prueba
 * tendría que construir cuarenta campos irrelevantes, y el campo que de
 * verdad se está probando quedaría escondido entre ellos.
 */
