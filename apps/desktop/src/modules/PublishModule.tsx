/**
 * Publicación.
 *
 * La pantalla se construye alrededor de una comprobación previa, no de un
 * botón. Publicar un recorrido con referencias rotas, propuestas automáticas
 * sin revisar o credenciales en el manifiesto es exactamente lo que el plan
 * prohíbe, así que la interfaz enseña el resultado de la verificación antes
 * de ofrecer la acción, y la bloquea cuando hay errores.
 */
import { useCallback, useMemo, useState } from 'react';
import {
  findForbiddenKeys,
  hasBlockingProblems,
  toManifest,
  estimateBytes,
  planImage,
  planVrVariants,
  renditionWarnings,
  VR_VARIANT_PROFILES,
  type PublishQuality,
  walkSkin,
} from '@it360/domain';
import { VR_PROFILES, vrCompatibilityWarnings } from '@it360/viewer';
import {
  Badge,
  Button,
  Callout,
  cx,
  EmptyState,
  Field,
  IconCheck,
  IconClose,
  IconDownload,
  IconExperimental,
  IconLock,
  IconPublish,
  IconWeb,
  NumberInput,
  Spinner,
  Panel,
  ProgressBar,
  PropertyList,
  PropertyRow,
  Select,
  Switch,
  TextInput,
  useToast,
} from '@it360/ui';
import type { ProjectStore } from '../state/project-store';
import { APP_VERSION } from '../version';
import { publishProject } from '../platform/publish-files';
import { importMediaFile } from '../platform/media-import';

export interface PublishModuleProps {
  readonly store: ProjectStore;
  /** Contenido de los medios del proyecto, por ruta relativa. */
  readonly mediaFiles: ReadonlyMap<string, Uint8Array>;
}

interface PreflightCheck {
  readonly id: string;
  readonly label: string;
  readonly detail: string;
  readonly status: 'pass' | 'warn' | 'fail';
}

export function PublishModule({ store, mediaFiles }: PublishModuleProps): JSX.Element {
  const { push } = useToast();
  const [target, setTarget] = useState<'web' | 'offline' | 'portable' | 'scorm'>('web');
  const [courseId, setCourseId] = useState('');
  const [generating, setGenerating] = useState(false);
  const project = store.project;
  const quality = project.settings.publishQuality;

  /**
   * Comprobaciones previas.
   *
   * Cada una responde a un requisito concreto del plan y ninguna se puede
   * «pasar por alto» desde la interfaz: las que fallan impiden publicar. Las
   * advertencias sí dejan continuar, porque excluir una escena o dejar una
   * nota abierta son decisiones legítimas del autor.
   */
  const checks = useMemo<readonly PreflightCheck[]>(() => {
    const result: PreflightCheck[] = [];
    const errors = store.integrity.filter((p) => p.severity === 'error');
    const warnings = store.integrity.filter((p) => p.severity === 'warning');

    result.push({
      id: 'integrity',
      label: 'Integridad referencial',
      status: errors.length > 0 ? 'fail' : warnings.length > 0 ? 'warn' : 'pass',
      detail:
        errors.length > 0
          ? `${errors.length} referencia(s) sin resolver. ${errors[0]?.message ?? ''}`
          : warnings.length > 0
            ? `${warnings.length} aviso(s) sin consecuencia para la publicación.`
            : 'Todas las referencias resuelven.',
    });

    const publishable = project.scenes.filter((s) => !s.excludedFromPublish);
    result.push({
      id: 'scenes',
      label: 'Escenas publicables',
      status: publishable.length === 0 ? 'fail' : 'pass',
      detail:
        publishable.length === 0
          ? 'No hay ninguna escena incluida en la publicación.'
          : `${publishable.length} de ${project.scenes.length} escena(s) se publicarán.`,
    });

    const entry = project.settings.entrySceneId;
    const entryScene = publishable.find((s) => s.id === entry);
    result.push({
      id: 'entry',
      label: 'Escena de entrada',
      status: entry === null ? 'warn' : entryScene === undefined ? 'fail' : 'pass',
      detail:
        entry === null
          ? 'Sin escena de entrada: el visor abrirá la primera de la lista.'
          : entryScene === undefined
            ? 'La escena de entrada no existe o está excluida de la publicación.'
            : `El recorrido abrirá en «${entryScene.title}».`,
    });

    const unreviewed = project.scenes.flatMap((s) =>
      s.hotspots.filter((h) => h.autoGenerated && !h.reviewed),
    );
    result.push({
      id: 'unreviewed',
      label: 'Propuestas automáticas sin revisar',
      status: unreviewed.length > 0 ? 'warn' : 'pass',
      detail:
        unreviewed.length > 0
          ? `${unreviewed.length} marcador(es) generados automáticamente no se publicarán hasta confirmarse.`
          : 'No hay propuestas pendientes de revisión.',
    });

    /*
     * Compatibilidad con visores VR (N06, N07, N12).
     *
     * Se comprueba aquí y no en el editor de escenas porque el fallo que
     * importa es publicar: con las gafas puestas, un marcador de un tipo que
     * VR no admite simplemente no está, y lo que falta puede ser justo el que
     * lleva a la escena siguiente. Es un aviso y no un bloqueo —un recorrido
     * puede publicarse para escritorio a sabiendas— pero tiene que verse antes
     * de dar a publicar.
     */
    const vrProfile = VR_PROFILES['standalone'];
    if (vrProfile !== undefined) {
      const vrWarnings = project.scenes
        .filter((scene) => !scene.excludedFromPublish)
        .flatMap((scene) =>
          vrCompatibilityWarnings(
            scene.hotspots,
            project.skins.flatMap((skin) =>
              [...walkSkin(skin.root)].map((entry) => entry.node.config.kind),
            ),
            vrProfile,
          ).map((warning) => `${scene.title}: ${warning}`),
        );

      // Los avisos de componentes se repiten por escena, porque las interfaces
      // son del proyecto: se muestran una sola vez.
      const unicos = [...new Set(vrWarnings.map((w) => w.replace(/^[^:]+: /, '')))];

      result.push({
        id: 'vr',
        label: 'Compatibilidad con visores VR',
        status: unicos.length > 0 ? 'warn' : 'pass',
        detail:
          unicos.length > 0
            ? `${unicos[0]}${unicos.length > 1 ? ` (y ${unicos.length - 1} aviso(s) más)` : ''}`
            : `Perfil «${vrProfile.name}»: nada que impida usar el recorrido con gafas.`,
      });
    }

    const missingMedia = project.scenes.filter(
      (s) => s.mediaId === null || !project.media.some((m) => m.id === s.mediaId),
    );
    result.push({
      id: 'media',
      label: 'Imágenes de las escenas',
      status: missingMedia.length > 0 ? 'fail' : 'pass',
      detail:
        missingMedia.length > 0
          ? `${missingMedia.length} escena(s) sin panorámica asignada.`
          : 'Todas las escenas tienen su imagen.',
    });

    // Sólo lectura verificada: el manifiesto se construye y se recorre
    // buscando claves prohibidas antes de ofrecer la descarga.
    // `toManifest` valida el proyecto y lanza si no cumple el esquema. Se
    // captura aquí porque esta pantalla es precisamente la que debe informar
    // de que el proyecto no se puede publicar: dejar escapar la excepción
    // tumbaría la comprobación previa entera y el usuario vería una pantalla
    // en blanco en lugar del motivo.
    try {
      const manifest = toManifest(project, {
        publishedAt: new Date().toISOString(),
        appVersion: APP_VERSION,
        offlineCapable: false,
      });
      const leaked = findForbiddenKeys(manifest);
      result.push({
        id: 'secrets',
        label: 'Credenciales fuera del paquete',
        status: leaked.length > 0 ? 'fail' : 'pass',
        detail:
          leaked.length > 0
            ? `El manifiesto contiene claves prohibidas: ${leaked.join(', ')}.`
            : 'El manifiesto publicado no contiene tokens, referencias a secretos ni conexiones.',
      });
    } catch (cause) {
      result.push({
        id: 'secrets',
        label: 'Manifiesto de publicación',
        status: 'fail',
        detail: `El proyecto no cumple el esquema y no se puede construir el manifiesto: ${String(cause).slice(0, 300)}`,
      });
    }

    const scripting = project.settings.scripting;
    const scriptsLive = scripting.mode !== 'disabled' && scripting.allowInPublished;
    result.push({
      id: 'scripting',
      label: 'JavaScript personalizado',
      status: scriptsLive ? 'warn' : 'pass',
      detail: scriptsLive
        ? `Modo «${scripting.mode}» con ejecución permitida en el paquete: ${scripting.approvals.length} guion(es) aprobado(s), en contexto aislado y con ${scripting.timeoutMs} ms de límite.`
        : scripting.mode === 'disabled'
          ? 'Deshabilitado, como exige la configuración por defecto.'
          : 'Habilitado en el editor pero no en el paquete publicado.',
    });

    return result;
  }, [project, store.integrity]);

  const failing = checks.filter((c) => c.status === 'fail');
  const warning = checks.filter((c) => c.status === 'warn');
  const blocked = failing.length > 0 || hasBlockingProblems(store.integrity);
  const passed = checks.length - failing.length - warning.length;

  const setQuality = (patch: Partial<PublishQuality>): void => {
    store.updateProject('Cambiar calidad de publicación', {
      settings: { ...project.settings, publishQuality: { ...quality, ...patch } },
    });
  };

  /**
   * Genera el paquete en la carpeta que elija el usuario.
   *
   * El bloqueo por comprobaciones fallidas se respeta aquí también, y no sólo
   * deshabilitando el botón: el estado puede cambiar entre el renderizado y la
   * pulsación, y la comprobación que importa es la del momento en que se
   * escribe.
   */
  const onGenerate = useCallback(async () => {
    if (blocked) {
      push({ tone: 'alarm', title: 'Corrija las comprobaciones fallidas antes de publicar' });
      return;
    }

    setGenerating(true);
    const result = await publishProject({
      target: target === 'portable' ? 'offline' : target,
      project,
      mediaFiles,
      ...(courseId.trim().length > 0 ? { courseId: courseId.trim() } : {}),
    });
    setGenerating(false);

    if (!result.ok) {
      push({
        tone: 'alarm',
        title: 'No se pudo generar el paquete',
        description: `${result.error.message}${result.error.recovery !== undefined ? ` ${result.error.recovery}` : ''}`,
      });
      return;
    }
    if (result.value === null) return; // Diálogo cancelado.

    const summary = result.value.imageSummary;
    push({
      tone: result.value.warnings.length > 0 ? 'warning' : 'nominal',
      title: `Paquete generado (${(result.value.totalBytes / 1_000_000).toFixed(1)} MB)`,
      description: [
        summary,
        result.value.warnings.length > 0
          ? `${result.value.warnings.length} advertencia(s) en el informe: ${result.value.reportPath}.`
          : `Escrito en ${result.value.folder}.`,
      ]
        .filter((part) => part !== undefined && part !== '')
        .join(' '),
    });
  }, [blocked, target, project, mediaFiles, courseId, push]);

  const estimatedBytes = useMemo(() => {
    /* Estimación sobre el peso real de cada medio, no sobre una fórmula de
       resolución por calidad: la anterior daba la misma cifra para una
       panorámica de 2 MB y otra de 60 MB, porque no miraba los archivos. */
    let total = 0;
    for (const entry of project.media) {
      total += estimateBytes(entry, planImage(entry, quality));
    }
    return total;
  }, [project.media, quality]);

  /** Vídeos del proyecto: los únicos que admiten versiones (V04). */
  const videos = useMemo(
    () => project.media.filter((entry) => entry.kind === 'video' && !entry.quarantined),
    [project.media],
  );

  const [importingRendition, setImportingRendition] = useState(false);

  /**
   * Da de alta otra versión de un vídeo (V04).
   *
   * La altura se toma de la medición real del archivo y no se pregunta: el
   * autor ya sabe qué exportó, y un número escrito a mano que no coincida con
   * el archivo haría que el visor eligiera mal sin que nada lo delatara.
   */
  const addRendition = useCallback(
    async (videoId: string, file: File): Promise<void> => {
      setImportingRendition(true);
      try {
        const result = await importMediaFile(file, project.media, { folder: 'media/video' });
        if (!result.ok) {
          push({
            tone: 'alarm',
            title: 'No se pudo añadir la versión',
            description: `${result.error.message}${result.error.recovery === undefined ? '' : ` ${result.error.recovery}`}`,
          });
          return;
        }

        const added = result.value.media;
        if (added.kind !== 'video') {
          push({
            tone: 'alarm',
            title: 'Eso no es un vídeo',
            description: `«${added.originalName}» no es un archivo de vídeo, así que no puede ser otra versión de uno.`,
          });
          return;
        }

        if (added.height === null) {
          push({
            tone: 'alarm',
            title: 'No se pudo medir la versión',
            description:
              'Sin conocer su altura no se puede saber cuándo entregarla. Exporte el archivo con otra herramienta o compruebe que no está dañado.',
          });
          return;
        }

        const primary = project.media.find((entry) => entry.id === videoId);
        if (primary === undefined) return;

        const media = result.value.reused ? project.media : [...project.media, added];
        store.updateProject(`Añadir versión ${added.height}p de ${primary.originalName}`, {
          media: media.map((entry) =>
            entry.id !== videoId
              ? entry
              : {
                  ...entry,
                  renditions: [
                    ...entry.renditions.filter((r) => r.mediaId !== added.id),
                    { mediaId: added.id, heightPx: added.height ?? 0 },
                  ],
                },
          ),
        });

        push({
          tone: 'nominal',
          title: `Versión de ${added.height}p añadida`,
          description: `Se entregará a los dispositivos que no puedan con «${primary.originalName}».`,
        });
      } finally {
        setImportingRendition(false);
      }
    },
    [project.media, push, store],
  );

  /**
   * Quita una versión de la escalera.
   *
   * El archivo se queda en la biblioteca de medios: puede estar en uso en otro
   * sitio, y borrarlo por quitarlo de aquí destruiría trabajo ajeno a esta
   * pantalla. Si no se usa en ninguna parte, el plan de publicación ya lo deja
   * fuera del paquete por su cuenta.
   */
  const removeRendition = useCallback(
    (videoId: string, renditionId: string): void => {
      const primary = project.media.find((entry) => entry.id === videoId);
      if (primary === undefined) return;

      store.updateProject(`Quitar una versión de ${primary.originalName}`, {
        media: project.media.map((entry) =>
          entry.id !== videoId
            ? entry
            : { ...entry, renditions: entry.renditions.filter((r) => r.mediaId !== renditionId) },
        ),
      });
    },
    [project.media, store],
  );

  /** Advertencias del plan que el autor debe leer antes de generar. */
  const planNotes = useMemo(() => {
    const notes = new Set<string>();
    for (const entry of project.media) {
      const note = planImage(entry, quality).note;
      if (note !== null && note !== 'no es una imagen') notes.add(note);
    }

    /* Versiones de vídeo (V04). El aviso es concreto —«exporte una versión de
       720p»— porque eso se puede hacer; «el vídeo es grande» no. */
    const byId = new Map(project.media.map((entry) => [entry.id, entry]));
    for (const entry of project.media) {
      if (entry.kind !== 'video') continue;
      for (const warning of renditionWarnings(entry, entry.renditions, byId)) {
        notes.add(warning);
      }
    }

    /* Juego de panorámicas para visor inmersivo (N12). Se cuenta antes de
       generar porque cambia el peso del paquete y el autor lo nota al
       subirlo; callarlo haría que descubriera la diferencia después. */
    for (const profile of VR_VARIANT_PROFILES) {
      const plan = planVrVariants(project.media, project.scenes, quality, profile);
      if (plan.note !== null && plan.variants.length > 0) notes.add(plan.note);
    }

    return [...notes];
  }, [project.media, project.scenes, quality]);

  return (
    <div className="module">
      <header className="module__head">
        <div>
          <h1 className="module__title">Publicación</h1>
          <p className="module__subtitle">
            Comprobación previa, calidad de imagen y destino. El paquete se genera en el contenedor de
            escritorio.
          </p>
        </div>
        <div className="module__head-actions">
          <Badge tone={blocked ? 'alarm' : warning.length > 0 ? 'warning' : 'nominal'} dot>
            {blocked
              ? `${failing.length} comprobación(es) fallida(s)`
              : warning.length > 0
                ? `${warning.length} advertencia(s)`
                : 'Listo para publicar'}
          </Badge>
        </div>
      </header>

      <div className="module__body">
        <Panel title="Comprobación previa" level="raised">
          <div style={{ marginBottom: 'var(--it-space-3)' }}>
            <ProgressBar
              value={checks.length === 0 ? null : passed / checks.length}
              label={`Comprobaciones superadas: ${passed} de ${checks.length}`}
              showValue
              tone={blocked ? 'alarm' : warning.length > 0 ? 'warning' : 'nominal'}
            />
          </div>
          <div className="integrity">
            {checks.map((check) => (
              <div
                key={check.id}
                className={cx('integrity__item', check.status === 'fail' && 'integrity__item--error')}
              >
                <span
                  className="integrity__entity"
                  style={{
                    color:
                      check.status === 'fail'
                        ? 'var(--it-color-status-alarm)'
                        : check.status === 'warn'
                          ? 'var(--it-color-status-warning)'
                          : 'var(--it-color-status-nominal)',
                  }}
                >
                  {check.status === 'fail' ? (
                    <IconClose size={13} />
                  ) : check.status === 'warn' ? (
                    <IconExperimental size={13} />
                  ) : (
                    <IconCheck size={13} />
                  )}
                </span>
                <div>
                  <p style={{ margin: 0, fontWeight: 'var(--it-weight-medium)' as never }}>{check.label}</p>
                  <p className="integrity__recovery" style={{ margin: 0 }}>
                    {check.detail}
                  </p>
                </div>
              </div>
            ))}
          </div>
        </Panel>

        <div className="module__grid">
          <Panel title="Destino" level="raised">
            <div style={{ display: 'grid', gap: 'var(--it-space-3)' }}>
              {(
                [
                  {
                    id: 'web' as const,
                    label: 'Sitio web estático',
                    detail: 'Carpeta con HTML, imágenes y manifiesto. Se sube a cualquier servidor.',
                    icon: <IconWeb size={15} />,
                  },
                  {
                    id: 'offline' as const,
                    label: 'Paquete sin conexión',
                    detail: 'ZIP autocontenido para verlo desde una memoria USB, sin servidor.',
                    icon: <IconDownload size={15} />,
                  },
                  {
                    id: 'portable' as const,
                    label: 'Visor portable',
                    detail: 'Ejecutable de un solo archivo para equipos sin instalación.',
                    icon: <IconPublish size={15} />,
                  },
                  {
                    id: 'scorm' as const,
                    label: 'Paquete SCORM 1.2',
                    detail: 'Para subir el recorrido de formación a un LMS corporativo.',
                    icon: <IconDownload size={15} />,
                  },
                ] satisfies readonly { id: typeof target; label: string; detail: string; icon: JSX.Element }[]
              ).map((option) => (
                <button
                  key={option.id}
                  type="button"
                  className={cx('targetcard', target === option.id && 'targetcard--active')}
                  aria-pressed={target === option.id}
                  onClick={() => setTarget(option.id)}
                >
                  <span className="targetcard__icon">{option.icon}</span>
                  <span>
                    <span className="targetcard__label">{option.label}</span>
                    <span className="targetcard__detail">{option.detail}</span>
                  </span>
                </button>
              ))}
            </div>
          </Panel>

          <Panel title="Calidad de imagen" level="raised">
            <div style={{ display: 'grid', gap: 'var(--it-space-3)' }}>
              <Field label="Formato" inline>
                {({ id }) => (
                  <Select
                    id={id}
                    size="sm"
                    value={quality.format}
                    onChange={(event) => setQuality({ format: event.currentTarget.value as PublishQuality['format'] })}
                  >
                    {/* Las etiquetas dicen lo que el codificador hace de
                        verdad. Antes WebP se anunciaba como «menor tamaño» y
                        es sin pérdida: pesa más que un JPEG. */}
                    <option value="jpeg">JPEG (menor tamaño, con pérdida)</option>
                    <option value="webp">WebP (sin pérdida, exacto y más grande)</option>
                    <option value="png">PNG (sin pérdida, el más grande)</option>
                    <option value="avif">AVIF (no disponible: se publica WebP)</option>
                  </Select>
                )}
              </Field>

              {planNotes.length > 0 && (
                <Callout tone="warning" title="Lo que se publicará no es exactamente lo elegido">
                  <ul style={{ margin: 0, paddingLeft: 'var(--it-space-4)' }}>
                    {planNotes.map((note) => (
                      <li key={note}>{note}</li>
                    ))}
                  </ul>
                </Callout>
              )}

              <Field
                label="Calidad"
                inline
                hint="Sólo se aplica en JPEG: los demás formatos de esta versión son sin pérdida."
              >
                {() => (
                  <NumberInput
                    value={quality.quality}
                    onValueChange={(value) => setQuality({ quality: value })}
                    min={40}
                    max={100}
                    step={1}
                    decimals={0}
                    aria-label="Calidad de compresión"
                  />
                )}
              </Field>

              <Field label="Borde máximo" inline hint="Se limita al máximo que admite la GPU del visor.">
                {() => (
                  <NumberInput
                    value={quality.maxEdgePx}
                    onValueChange={(value) => setQuality({ maxEdgePx: value })}
                    min={2048}
                    max={16384}
                    step={1024}
                    unit="px"
                    decimals={0}
                    aria-label="Borde máximo en píxeles"
                  />
                )}
              </Field>

              <Switch
                label="Dividir en teselas"
                checked={quality.tiled}
                onChange={(event) => setQuality({ tiled: event.currentTarget.checked })}
              />
              <Switch
                label="Incluir imagen de reserva sin teselar"
                checked={quality.includeFallback}
                onChange={(event) => setQuality({ includeFallback: event.currentTarget.checked })}
              />

              <PropertyList>
                <PropertyRow
                  label="Tamaño estimado"
                  mono
                  value={`≈ ${(estimatedBytes / 1_000_000).toFixed(0)} MB`}
                />
              </PropertyList>
              <p style={{ margin: 0, fontSize: 'var(--it-text-xs)', color: 'var(--it-color-text-tertiary)' }}>
                Es una estimación a partir de la resolución y la calidad elegidas. El tamaño real se conoce
                al generar el paquete.
              </p>
            </div>
          </Panel>

          {/* Versiones de vídeo (V04). Va en esta pantalla porque es donde el
              autor piensa en el peso de la entrega, y es donde aparece el
              aviso de la versión que falta. */}
          {videos.length > 0 && (
            <Panel title="Versiones de vídeo">
              <div className="panel__stack">
                <p
                  style={{
                    margin: 0,
                    fontSize: 'var(--it-text-xs)',
                    color: 'var(--it-color-text-tertiary)',
                  }}
                >
                  El recorrido entrega la versión que corresponde al dispositivo y a la red, y da
                  prioridad al ahorro de datos del visitante. Esta aplicación no reescala vídeo:
                  exporte las versiones con su editor y añádalas aquí.
                </p>

                {videos.map((entry) => (
                  <div key={entry.id} className="panel__stack">
                    <PropertyList>
                      <PropertyRow
                        label={entry.originalName}
                        value={entry.height === null ? 'altura desconocida' : `${entry.height}p`}
                        mono
                      />
                      {entry.renditions.map((rendition) => {
                        const media = project.media.find((m) => m.id === rendition.mediaId);
                        return (
                          <PropertyRow
                            key={rendition.mediaId}
                            label={`· ${media?.originalName ?? 'versión ausente del proyecto'}`}
                            value={
                              <span
                                style={{
                                  display: 'inline-flex',
                                  gap: 'var(--it-space-2)',
                                  alignItems: 'center',
                                }}
                              >
                                {rendition.heightPx}p
                                <Button
                                  size="sm"
                                  variant="ghost"
                                  onClick={() => removeRendition(entry.id, rendition.mediaId)}
                                >
                                  Quitar
                                </Button>
                              </span>
                            }
                          />
                        );
                      })}
                    </PropertyList>
                    <label className="csv-dialog__file">
                      <input
                        type="file"
                        accept="video/mp4,video/webm"
                        aria-label={`Añadir versión de ${entry.originalName}`}
                        disabled={importingRendition}
                        onChange={(event) => {
                          const file = event.currentTarget.files?.[0];
                          if (file !== undefined) void addRendition(entry.id, file);
                        }}
                      />
                    </label>
                  </div>
                ))}
              </div>
            </Panel>
          )}

          <Panel
            title={
              <span style={{ display: 'inline-flex', gap: 'var(--it-space-2)', alignItems: 'center' }}>
                <IconLock size={14} /> Lo que no sale del equipo
              </span>
            }
            level="raised"
          >
            {/* Enumerarlo explícitamente evita la pregunta que siempre llega
                de seguridad informática, y el manifiesto se verifica arriba
                con findForbiddenKeys. */}
            <PropertyList>
              <PropertyRow label="Tokens de InfluxDB" value="nunca" tone="nominal" />
              <PropertyRow label="Referencias a secretos" value="nunca" tone="nominal" />
              <PropertyRow label="Conexiones al historiador" value="nunca" tone="nominal" />
              <PropertyRow label="Usuarios y permisos" value="nunca" tone="nominal" />
              <PropertyRow label="Registro de auditoría" value="nunca" tone="nominal" />
              <PropertyRow
                label="Telemetría en el paquete"
                value="sólo histórico congelado si se pide"
              />
            </PropertyList>
          </Panel>
        </div>

        {blocked ? (
          <Callout tone="alarm" title="La publicación está bloqueada">
            Corrija las comprobaciones fallidas antes de generar el paquete. Publicar con referencias
            rotas produce un recorrido que falla en casa del cliente, y ahí el error cuesta mucho más
            que aquí.
          </Callout>
        ) : target === 'portable' ? (
          <Callout tone="experimental" title="El visor portable todavía no se genera">
            El ejecutable de un solo archivo está pendiente. Mientras tanto, el paquete sin conexión
            cumple el mismo propósito: se abre con el navegador del equipo y no necesita instalación.
          </Callout>
        ) : (
          <Callout
            tone="info"
            title="Generar el paquete"
            action={
              <Button
                variant="primary"
                icon={generating ? <Spinner size={14} /> : <IconPublish size={15} />}
                disabled={generating || (target === 'scorm' && courseId.trim().length === 0)}
                onClick={() => void onGenerate()}
              >
                {generating ? 'Generando…' : 'Generar paquete'}
              </Button>
            }
          >
            Se le pedirá la carpeta de destino. Junto al paquete se escribe un informe con lo que se
            publicó, lo que se dejó fuera y por qué.
          </Callout>
        )}

        {target === 'scorm' && (
          <Field
            label="Identificador del curso en el LMS"
            hint="Lo usa el LMS para registrar el curso; debe ser único en su plataforma."
          >
            {({ id }) => (
              <TextInput
                id={id}
                value={courseId}
                placeholder="IT360-U200"
                onChange={(event) => setCourseId(event.currentTarget.value)}
              />
            )}
          </Field>
        )}

        {project.scenes.length === 0 && (
          <EmptyState
            icon={<IconPublish size={30} />}
            title="Nada que publicar"
            description="Añada al menos una escena al recorrido."
          />
        )}
      </div>
    </div>
  );
}
