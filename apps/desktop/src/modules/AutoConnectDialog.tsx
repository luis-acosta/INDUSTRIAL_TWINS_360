/**
 * Revisión de las conexiones propuestas automáticamente.
 *
 * La pantalla existe porque el plan exige revisión humana de lo que produce un
 * algoritmo experimental, y «revisión» no significa un aviso que se cierra con
 * un clic. Significa poder ver cada propuesta con su confianza y su motivo,
 * desmarcar las que no convencen y aceptar sólo el resto.
 *
 * Nada se marca como revisado al aceptar. Los marcadores entran con
 * `reviewed: false` y el plan de publicación los deja fuera hasta que el autor
 * los confirma uno a uno en el inspector, que es donde los ve colocados sobre
 * la panorámica. Aceptar aquí significa «créalos para que pueda mirarlos», no
 * «doy fe de que están bien».
 */
import { useMemo, useState } from 'react';
import { newUuid, radToDeg, type Hotspot, type Project, type Uuid } from '@it360/domain';
import {
  EVIDENCE_LABELS,
  proposeConnections,
  summarizeProposals,
  type ConnectionProposal,
} from '@it360/editor';
import {
  Badge,
  Button,
  Callout,
  Checkbox,
  DataTable,
  Dialog,
  EmptyState,
  IconExperimental,
  useToast,
} from '@it360/ui';
import type { ProjectStore } from '../state/project-store';

export interface AutoConnectDialogProps {
  readonly open: boolean;
  readonly onClose: () => void;
  readonly store: ProjectStore;
}

export function AutoConnectDialog({ open, onClose, store }: AutoConnectDialogProps): JSX.Element {
  const project = store.project;
  const { push } = useToast();

  const result = useMemo(
    () =>
      proposeConnections({
        scenes: project.scenes,
        media: project.media,
        plans: project.plans,
        planMarkers: project.planMarkers,
      }),
    [project.scenes, project.media, project.plans, project.planMarkers],
  );

  const [rejected, setRejected] = useState<ReadonlySet<string>>(new Set());
  const keyOf = (proposal: ConnectionProposal): string =>
    `${proposal.fromSceneId}:${proposal.toSceneId}`;

  const accepted = result.proposals.filter((p) => !rejected.has(keyOf(p)));

  const sceneTitle = (id: Uuid): string =>
    project.scenes.find((s) => s.id === id)?.title ?? 'escena desconocida';

  const apply = (): void => {
    if (accepted.length === 0) return;

    // Un solo comando para todas las propuestas: el autor piensa en «aplicar
    // las conexiones» como una acción, y deshacerla debe retirarlas todas.
    const bySceneId = new Map<Uuid, Hotspot[]>();
    for (const proposal of accepted) {
      const now = new Date().toISOString();
      const hotspot = {
        id: newUuid(),
        sceneId: proposal.fromSceneId,
        name: `Ir a ${sceneTitle(proposal.toSceneId)}`,
        anchor: { space: 'spherical', yaw: proposal.yaw, pitch: proposal.pitch },
        geometry: { shape: 'icon', mediaId: null, builtinIcon: 'arrow', sizePx: 44 },
        style: {
          colorToken: 'experimental',
          colorOverride: null,
          opacity: 1,
          pulse: false,
          showLabel: false,
          labelTemplate: '',
          hoverScale: 1.15,
          transform: { scale: 1, roll: 0, tilt: 0, spin: 0, depth: 1 },
          projection: 'billboard',
        },
        actions: [
          {
            id: newUuid(),
            event: 'click',
            config: {
              type: 'goToScene',
              sceneId: proposal.toSceneId,
              entryMode: 'smart',
              transition: { kind: 'fade', durationMs: 450, useGeometry: false },
            },
            order: 0,
            delayMs: 0,
            focusDwellMs: 1200,
            once: false,
            requiresScore: null,
            enabled: true,
          },
        ],
        assetId: null,
        visibility: { desktop: true, tablet: true, mobile: true, vr: true },
        preload: 'lazy',
        locked: false,
        hiddenInEditor: false,
        tags: ['conexion-automatica'],
        autoGenerated: true,
        autoConfidence: proposal.confidence,
        // Sin revisar, siempre. Es lo que impide que esto se publique solo.
        reviewed: false,
        order: 0,
        createdAt: now,
        updatedAt: now,
      } as Hotspot;

      bySceneId.set(proposal.fromSceneId, [...(bySceneId.get(proposal.fromSceneId) ?? []), hotspot]);
    }

    const scenes: Project['scenes'] = project.scenes.map((scene) => {
      const added = bySceneId.get(scene.id);
      if (added === undefined) return scene;
      return {
        ...scene,
        hotspots: [
          ...scene.hotspots,
          ...added.map((hotspot, index) => ({ ...hotspot, order: scene.hotspots.length + index })),
        ],
      };
    });

    store.updateProject(`Aplicar ${accepted.length} conexión(es) propuesta(s)`, { scenes });
    push({
      tone: 'experimental',
      title: `${accepted.length} propuesta(s) añadida(s) sin revisar`,
      description:
        'Aparecen marcadas en el árbol y no se publicarán hasta que confirme cada una en el inspector.',
    });
    onClose();
  };

  return (
    <Dialog
      open={open}
      onClose={onClose}
      title="Proponer conexiones entre escenas"
      size="xl"
      footer={
        <>
          <Button variant="ghost" onClick={onClose}>
            Cancelar
          </Button>
          <Button variant="primary" disabled={accepted.length === 0} onClick={apply}>
            Añadir {accepted.length} propuesta(s) sin revisar
          </Button>
        </>
      }
    >
      <div style={{ display: 'grid', gap: 'var(--it-space-4)' }}>
        <Callout tone="experimental" title="Función experimental">
          {summarizeProposals(result)}
        </Callout>

        {result.proposals.length === 0 ? (
          <EmptyState
            icon={<IconExperimental size={28} />}
            title="Sin propuestas"
            description={
              result.evidence === null
                ? 'Las capturas no traen posición GPS y las escenas no están colocadas en un plano. Coloque los puntos en el plano o conecte las escenas a mano.'
                : 'Ninguna propuesta supera el umbral mínimo de confianza.'
            }
          />
        ) : (
          <DataTable
            label="Conexiones propuestas"
            rows={result.proposals}
            rowKey={keyOf}
            columns={[
              {
                id: 'accept',
                header: '',
                width: '40px',
                render: (row) => (
                  <Checkbox
                    checked={!rejected.has(keyOf(row))}
                    aria-label={`Añadir la conexión de ${sceneTitle(row.fromSceneId)} a ${sceneTitle(row.toSceneId)}`}
                    onChange={(event) =>
                      setRejected((current) => {
                        const next = new Set(current);
                        if (event.currentTarget.checked) next.delete(keyOf(row));
                        else next.add(keyOf(row));
                        return next;
                      })
                    }
                  />
                ),
              },
              { id: 'from', header: 'Desde', render: (row) => sceneTitle(row.fromSceneId) },
              { id: 'to', header: 'Hacia', render: (row) => sceneTitle(row.toSceneId) },
              {
                id: 'yaw',
                header: 'Azimut',
                mono: true,
                width: '90px',
                align: 'end',
                render: (row) => `${Math.round(radToDeg(row.yaw))}°`,
              },
              {
                id: 'distance',
                header: 'Distancia',
                mono: true,
                width: '100px',
                align: 'end',
                render: (row) => (row.distanceM === null ? '—' : `${row.distanceM} m`),
              },
              {
                id: 'confidence',
                header: 'Confianza',
                width: '110px',
                sortable: true,
                sortValue: (row) => row.confidence,
                render: (row) => (
                  <Badge
                    tone={row.confidence >= 0.7 ? 'nominal' : row.confidence >= 0.45 ? 'warning' : 'experimental'}
                  >
                    {(row.confidence * 100).toFixed(0)} %
                  </Badge>
                ),
              },
              {
                id: 'evidence',
                header: 'Señal',
                width: '180px',
                render: (row) => EVIDENCE_LABELS[row.evidence],
              },
              { id: 'reason', header: 'Motivo', render: (row) => row.reason },
            ]}
          />
        )}

        {result.skipped.length > 0 && (
          <Callout tone="warning" title={`${result.skipped.length} escena(s) sin considerar`}>
            {result.skipped.map((s) => s.reason).join(' ')}
          </Callout>
        )}
      </div>
    </Dialog>
  );
}
